	#region Method Implementation

	private static void RenderMethodImplementation(
		CodeWriter w,
		FlatMethodModel method,
		HashSet<string> multiOverloadInterceptors,
		HashSet<string> multiOverloadStubOverrideInterceptors,
		HashSet<string> multiOverloadGenericStubOverrideInterceptors,
		EquatableArray<FlatGenericMethodHandlerGroup> genericStubOverrideHandlerGroups)
	{
		// Handle method delegation (e.g., IRule.RunRule(IValidateBase) delegates to IRule<T>.RunRule(T))
		if (method.DelegationTarget != null && method.DelegationTargetInterface != null)
		{
			RenderMethodDelegation(w, method);
			return;
		}

		// Generic methods use method-based Return/Call API via typed handlers
		if (method.IsGenericMethod)
		{
			RenderGenericMethodImplementation(w, method, multiOverloadGenericStubOverrideInterceptors, genericStubOverrideHandlerGroups);
			return;
		}

		// User-defined methods with base class pattern: record call, check Return/Call, then delegate to virtual method
		if (method.HasStubOverride)
		{
			RenderStubOverrideImplementation(w, method, multiOverloadStubOverrideInterceptors);
			return;
		}

		// Determine if this method is part of an overload group (needs suffixed Invoke)
		var isMultiOverload = multiOverloadInterceptors.Contains(method.InterceptorName);
		var invokeSuffix = isMultiOverload ? $"_{GetSignatureSuffix(method)}" : "";

		// Non-generic methods use the new Invoke pattern
		w.Line($"{method.RefReturnPrefix}{method.ReturnType} {method.DeclaringInterface}.{method.MethodName}({method.ParameterDeclarations})");
		using (w.Braces())
		{
			// Build invoke args (includes Strict, no stub parameter)
			var invokeArgs = method.Parameters.Count > 0
				? "Strict, " + string.Join(", ", method.Parameters.Select(p => $"{p.RefPrefix}{p.EscapedName}"))
				: "Strict";

			if (method.IsRefReturn)
			{
				var invokeRefSuffix = isMultiOverload ? $"_{GetSignatureSuffix(method)}" : "";
				var backingField = isMultiOverload ? $"_refReturnBacking_{GetSignatureSuffix(method)}" : "_refReturnBacking";
				w.Line($"{method.InterceptorName}.InvokeRef{invokeRefSuffix}({invokeArgs});");
				w.Line($"return ref {method.InterceptorName}.{backingField};");
			}
			else if (method.IsVoid)
				w.Line($"{method.InterceptorName}.Invoke{invokeSuffix}({invokeArgs});");
			else
				w.Line($"return {method.InterceptorName}.Invoke{invokeSuffix}({invokeArgs});");
		}
		w.Line();
	}

	/// <summary>
	/// Renders the explicit interface implementation for a method with stub override (base class pattern).
	/// Priority chain: When chains > Sequences > Return/Call > Stub override (virtual method with _ suffix).
	/// The unified interceptor handles all logic including stub override fallback.
	/// </summary>
	private static void RenderStubOverrideImplementation(CodeWriter w, FlatMethodModel method, HashSet<string> multiOverloadStubOverrideInterceptors)
	{
		// Determine if this stub override is part of an overload group (needs suffixed Invoke)
		var isMultiOverload = multiOverloadStubOverrideInterceptors.Contains(method.InterceptorName);
		var invokeSuffix = isMultiOverload ? $"_{GetSignatureSuffix(method)}" : "";

		w.Line($"{method.ReturnType} {method.DeclaringInterface}.{method.MethodName}({method.ParameterDeclarations})");
		using (w.Braces())
		{
			// Build invoke args (includes Strict, stub reference, and method parameters)
			var invokeArgs = method.Parameters.Count > 0
				? "Strict, this, " + string.Join(", ", method.Parameters.Select(p => $"{p.RefPrefix}{p.EscapedName}"))
				: "Strict, this";

			if (method.IsVoid)
				w.Line($"{method.InterceptorName}.Invoke{invokeSuffix}({invokeArgs});");
			else
				w.Line($"return {method.InterceptorName}.Invoke{invokeSuffix}({invokeArgs});");
		}
		w.Line();
	}

	private static void RenderGenericMethodImplementation(
		CodeWriter w,
		FlatMethodModel method,
		HashSet<string> multiOverloadGenericStubOverrideInterceptors,
		EquatableArray<FlatGenericMethodHandlerGroup> genericStubOverrideHandlerGroups)
	{
		// For methods with unconstrained nullable type parameters (T? without where T : class),
		// we must disable nullable context. Without this, the compiler interprets T? as Nullable<T>
		// (CS0453) or reports nullability mismatch (CS8769). The type strings are already stripped
		// of ? for these type parameters by the builder.
		if (method.NeedsNullableDisable)
			w.Line("#nullable disable");

		// Generic methods use the method-based Return/Call API via typed handlers
		w.Line($"{method.ReturnType} {method.DeclaringInterface}.{method.MethodName}{method.TypeParameterDecl}({method.ParameterDeclarations}){method.ConstraintClauses}");
		using (w.Braces())
		{
			// Initialize out parameters
			foreach (var p in method.Parameters.Where(p => p.RefKind == Microsoft.CodeAnalysis.RefKind.Out))
			{
				w.Line($"{p.EscapedName} = default!;");
			}

			var interceptorAccess = $"{method.InterceptorName}{method.OfTypeAccess}";

			// Generic methods use RecordCallArgs (excludes generic-typed params)
			var recordCallArgs = method.RecordCallArgs;

			// Record the call
			w.Line($"{interceptorAccess}.RecordCall({recordCallArgs});");

			// Build onCall args (no stub parameter)
			var callArgs = method.Parameters.Count > 0
				? string.Join(", ", method.Parameters.Select(p => $"{p.RefPrefix}{p.EscapedName}"))
				: "";

			if (method.IsVoid)
			{
				w.Line($"if ({interceptorAccess}.Callback is {{ }} callCallback)");
				w.Line($"{{ callCallback({callArgs}); return; }}");
				w.Line($"if (Strict) throw global::KnockOff.StubException.NotConfigured(\"{method.SimpleInterfaceName}\", \"{method.MethodName}\");");
				// Generic methods don't support stub overrides - just return for void
			}
			else if (method.ThrowsOnDefault)
			{
				w.Line($"if ({interceptorAccess}.Callback is {{ }} callback)");
				w.Line($"\treturn callback({callArgs});");
				w.Line($"if (Strict) throw global::KnockOff.StubException.NotConfigured(\"{method.SimpleInterfaceName}\", \"{method.MethodName}\");");
				w.Line($"throw new global::System.InvalidOperationException(\"No implementation provided for {method.MethodName}. Use {interceptorAccess}.{(method.IsVoid ? "Call" : "Return")}(callback).\");");
			}
			else
			{
				w.Line($"if ({interceptorAccess}.Callback is {{ }} callback)");
				w.Line($"\treturn callback({callArgs});");
				w.Line($"if (Strict) throw global::KnockOff.StubException.NotConfigured(\"{method.SimpleInterfaceName}\", \"{method.MethodName}\");");
				w.Line($"return {method.DefaultExpression};");
			}
		}

		if (method.NeedsNullableDisable)
			w.Line("#nullable restore");
		w.Line();
	}

	/// <summary>
	/// Gets the signature suffix for a generic stub override from the handler groups.
	/// </summary>
	private static string GetGenericStubOverrideSignatureSuffix(
		FlatMethodModel method,
		EquatableArray<FlatGenericMethodHandlerGroup> handlerGroups)
	{
		var group = handlerGroups.FirstOrDefault(g => g.InterceptorName == method.InterceptorName);
		if (group == null)
			return "";

		// Strip angle brackets from method's type parameter list for comparison
		// TypeParameterList has angle brackets (e.g., "<T>"), TypeParameterNames does not (e.g., "T")
		var methodTypeParams = method.TypeParameterList.TrimStart('<').TrimEnd('>');

		// Find the type arity group matching this method's type parameters
		var arityGroup = group.TypeArityGroups.FirstOrDefault(a => a.TypeParameterNames == methodTypeParams);
		if (arityGroup == null)
			return "";

		// Find the signature group matching this method
		// We need to match by parameter types
		var paramArray = method.Parameters.GetArray() ?? Array.Empty<ParameterModel>();
		foreach (var sig in arityGroup.SignatureGroups)
		{
			var sigParams = sig.AllParameters.GetArray() ?? Array.Empty<ParameterModel>();
			if (paramArray.Length == sigParams.Length)
			{
				var match = true;
				for (int i = 0; i < paramArray.Length; i++)
				{
					if (paramArray[i].Type != sigParams[i].Type)
					{
						match = false;
						break;
					}
				}
				if (match)
					return sig.SignatureSuffix;
			}
		}

		return "";
	}

	private static void RenderMethodDelegation(CodeWriter w, FlatMethodModel method)
	{
		var target = method.DelegationTarget!;
		var targetInterface = method.DelegationTargetInterface!;

		// Build parameter cast expressions for delegation
		var memberParams = method.Parameters.GetArray() ?? System.Array.Empty<KnockOff.Model.Shared.ParameterModel>();
		var targetParams = target.Parameters.GetArray() ?? System.Array.Empty<ParameterInfo>();

		var castArgs = new List<string>();
		for (int i = 0; i < memberParams.Length; i++)
		{
			var memberType = memberParams[i].Type;
			var targetType = targetParams[i].Type;
			var paramName = memberParams[i].EscapedName;

			if (memberType != targetType)
			{
				// Cast to the target type
				castArgs.Add($"({targetType}){paramName}");
			}
			else
			{
				castArgs.Add(paramName);
			}
		}

		var argList = string.Join(", ", castArgs);

		// Expression-bodied members don't use 'return' keyword
		if (method.NeedsNullableDisable)
			w.Line("#nullable disable");
		w.Line($"{method.ReturnType} {method.DeclaringInterface}.{method.MethodName}{method.TypeParameterDecl}({method.ParameterDeclarations}){method.ConstraintClauses}");
		w.Line($"\t=> (({targetInterface})this).{target.Name}({argList});");
		if (method.NeedsNullableDisable)
			w.Line("#nullable restore");
		w.Line();
	}

