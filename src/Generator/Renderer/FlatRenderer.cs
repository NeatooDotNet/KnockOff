// src/Generator/Renderer/FlatRenderer.cs
#nullable enable
using System.Collections.Generic;
using System.Linq;
using KnockOff;
using KnockOff.Builder;
using KnockOff.Model.Flat;
using KnockOff.Model.Shared;
using KnockOff.Renderer.Shared;

namespace KnockOff.Renderer;

/// <summary>
/// Renders FlatGenerationUnit to source code string.
/// Pure emission - no decisions, just output what the model says.
/// </summary>
internal static class FlatRenderer
{
	public static string Render(FlatGenerationUnit unit)
	{
		var w = new CodeWriter();

		w.Line("// <auto-generated/>");
		w.Line("#nullable enable");
		w.Line();

		// Always include System.Linq - needed for .Sum() in overload TotalCallCount and generic methods
		w.Line("using System.Linq;");
		w.Line();

		// Namespace
		if (!string.IsNullOrEmpty(unit.Namespace))
		{
			w.Line($"namespace {unit.Namespace};");
			w.Line();
		}

		// Open containing type wrappers for nested classes
		foreach (var containingType in unit.ContainingTypes)
		{
			var accessMod = string.IsNullOrEmpty(containingType.AccessModifier)
				? ""
				: containingType.AccessModifier + " ";
			w.Line($"{accessMod}partial {containingType.Keyword} {containingType.Name}");
			w.Line("{");
		}

		// Class declaration with interfaces
		var interfaces = string.Join(", ", unit.InterfaceList);
		var typeParams = FormatTypeParameters(unit.TypeParameters);
		var constraints = FormatConstraints(unit.TypeParameters);

		// Calculate the class name with type parameters for delegate signatures
		var classNameWithTypeParams = $"{unit.ClassName}{typeParams}";

		// Base class for stub overrides
		var baseClass = $"{unit.ClassName}Base{typeParams}";

		using (w.Block($"partial class {unit.ClassName}{typeParams} : {baseClass}, {interfaces}, global::KnockOff.IKnockOffStub{constraints}"))
		{
			// Track rendered interceptors to avoid duplicates
			// (Multiple interface members may map to the same interceptor)
			var renderedInterceptorClasses = new HashSet<string>();

			// Generic method interfaces if needed
			if (unit.HasGenericMethods)
				RenderGenericMethodInterfaces(w);

			// Interceptor classes (deduplicated by interceptor name)
			var propertyOptions = new PropertyInterceptorRenderOptions(
				BaseIndent: 0,
				IncludeStrictParameter: true,
				StrictAccessExpression: "strict");
			foreach (var prop in unit.Properties)
			{
				if (renderedInterceptorClasses.Add(prop.InterceptorClassName))
				{
					var unifiedModel = ModelAdapters.ToUnifiedPropertyModel(prop);
					PropertyInterceptorRenderer.RenderInterceptorClass(w, unifiedModel, propertyOptions);
				}
			}

			var indexerOptions = new IndexerInterceptorRenderOptions(
				BaseIndent: 0,
				IncludeStrictParameter: true,
				StrictAccessExpression: "strict");
			foreach (var indexer in unit.Indexers)
			{
				if (renderedInterceptorClasses.Add(indexer.InterceptorClassName))
				{
					var unifiedModel = ModelAdapters.ToUnifiedIndexerModel(indexer);
					IndexerInterceptorRenderer.RenderInterceptorClass(w, unifiedModel, indexerOptions);
				}
			}

			// Render indexer container classes for groups with multiple indexers
			foreach (var group in unit.IndexerGroups)
			{
				if (group.Indexers.Count > 1 && renderedInterceptorClasses.Add(group.ContainerClassName))
					RenderIndexerContainerClass(w, group);
			}

			// Render method interceptor classes using groups (handles overloads)
			// Use shared renderer for unified API between inline and flat stubs
			foreach (var group in unit.MethodGroups)
			{
				if (renderedInterceptorClasses.Add(group.InterceptorClassName))
				{
					var unifiedModel = ModelAdapters.ToUnifiedModel(group, unit.ClassName, typeParams);
					var options = new InterceptorRenderOptions(
						BaseIndent: 0,
						IncludeStrictParameter: true,
						StrictAccessExpression: "strict");
					MethodInterceptorRenderer.RenderInterceptorClass(w, unifiedModel, options);
				}
			}

			// Render user-defined method interceptor classes (full interceptor with When/Sequence support)
			foreach (var group in unit.StubOverrideGroups)
			{
				if (renderedInterceptorClasses.Add(group.InterceptorClassName))
				{
					var unifiedModel = ModelAdapters.ToUnifiedModel(group, unit.ClassName, typeParams);
					var options = new InterceptorRenderOptions(
						BaseIndent: 0,
						IncludeStrictParameter: true,
						StrictAccessExpression: "strict",
						StubOverrideFallback: true,
						StubTypeName: classNameWithTypeParams);
					MethodInterceptorRenderer.RenderInterceptorClass(w, unifiedModel, options);
				}
			}

			foreach (var handler in unit.GenericMethodHandlers)
			{
				if (renderedInterceptorClasses.Add(handler.InterceptorClassName))
					RenderGenericMethodHandler(w, handler, classNameWithTypeParams);
			}

			// Render generic stub override handler groups (for overloaded generic stub overrides)
			foreach (var handlerGroup in unit.GenericStubOverrideHandlerGroups)
			{
				if (renderedInterceptorClasses.Add(handlerGroup.InterceptorClassName))
					RenderGenericStubOverrideHandlerGroup(w, handlerGroup, classNameWithTypeParams);
			}

			foreach (var evt in unit.Events)
			{
				if (renderedInterceptorClasses.Add(evt.InterceptorClassName))
					RenderEventInterceptorClass(w, evt);
			}

			// Interceptor properties (public access to interceptors)
			RenderInterceptorProperties(w, unit);

			// Standard members (Strict mode, Object accessor)
			RenderStandardMembers(w, unit);

			// Source(T) methods for each interface in the hierarchy
			RenderSourceMethods(w, unit);

			// Build set of interceptor names that have multiple UNIQUE overloads (need suffixed Invoke)
			var multiOverloadInterceptors = new HashSet<string>(
				unit.MethodGroups
					.Where(g => g.Methods.Select(GetSignatureSuffix).Distinct().Count() > 1)
					.Select(g => g.InterceptorName));

			// Build set of stub override interceptor names that have multiple UNIQUE overloads (need suffixed RecordCall)
			var multiOverloadStubOverrideInterceptors = new HashSet<string>(
				unit.StubOverrideGroups
					.Where(g => g.Methods.Select(GetSignatureSuffix).Distinct().Count() > 1)
					.Select(g => g.InterceptorName));

			// Build set of generic stub override interceptor names that have multiple overloads (need suffixed RecordCall/Callback)
			// A generic handler group needs suffixes if it has multiple type arities OR multiple signatures per arity
			var multiOverloadGenericStubOverrideInterceptors = new HashSet<string>(
				unit.GenericStubOverrideHandlerGroups
					.Where(g => g.TypeArityGroups.Count > 1 ||
					            g.TypeArityGroups.Any(a => a.SignatureGroups.Count > 1))
					.Select(g => g.InterceptorName));

			// Build indexer access map for multi-indexer groups
			var indexerAccessMap = BuildIndexerAccessMap(unit.IndexerGroups);

			// Explicit interface implementations (NOT deduplicated - one per interface member)
			foreach (var prop in unit.Properties)
				RenderPropertyImplementation(w, prop);

			foreach (var indexer in unit.Indexers)
				RenderIndexerImplementation(w, indexer, indexerAccessMap);

			foreach (var method in unit.Methods)
				RenderMethodImplementation(w, method, multiOverloadInterceptors, multiOverloadStubOverrideInterceptors, multiOverloadGenericStubOverrideInterceptors, unit.GenericStubOverrideHandlerGroups);

			foreach (var evt in unit.Events)
				RenderEventImplementation(w, evt);
		}

		// Close containing type wrappers for nested classes
		for (int i = 0; i < unit.ContainingTypes.Count; i++)
		{
			w.Line("}");
		}

		return w.ToString();
	}

	/// <summary>
	/// Renders the base class file for standalone stubs.
	/// Contains virtual protected methods for each interface method, suffixed with '_'.
	/// Users can override these methods to provide default implementations.
	/// </summary>
	public static string RenderBaseClass(FlatGenerationUnit unit)
	{
		var w = new CodeWriter();

		w.Line("// <auto-generated/>");
		w.Line("#nullable enable");
		w.Line();

		// Namespace
		if (!string.IsNullOrEmpty(unit.Namespace))
		{
			w.Line($"namespace {unit.Namespace};");
			w.Line();
		}

		// Open containing type wrappers for nested classes
		foreach (var containingType in unit.ContainingTypes)
		{
			var accessMod = string.IsNullOrEmpty(containingType.AccessModifier)
				? ""
				: containingType.AccessModifier + " ";
			w.Line($"{accessMod}partial {containingType.Keyword} {containingType.Name}");
			w.Line("{");
		}

		// Base class declaration with type parameters and constraints
		var typeParams = FormatTypeParameters(unit.TypeParameters);
		var constraints = FormatConstraints(unit.TypeParameters);

		using (w.Block($"public class {unit.ClassName}Base{typeParams}{constraints}"))
		{
			// Generate virtual protected methods for each non-generic interface method
			// Generic methods are excluded from the base class pattern per design decision
			//
			// When multiple interfaces have the same method signature but different return types
			// (e.g., ISet<T>.Add returns bool, ICollection<T>.Add returns void), we must pick one.
			// We prefer the non-void version as it provides more functionality.
			var methodsToRender = new Dictionary<string, FlatMethodModel>();

			foreach (var method in unit.Methods)
			{
				// Skip generic methods - they use .Of<T>() pattern only
				if (method.IsGenericMethod)
					continue;

				// Skip delegation targets (these are synthetic methods)
				if (method.DelegationTarget != null)
					continue;

				// Key by method name + parameter types ONLY (excluding return type)
				// C# does not allow overloading by return type, so we must pick one when
				// multiple interfaces have same method name/params but different returns
				var signatureKey = GetParameterOnlySignatureKey(method);

				if (methodsToRender.TryGetValue(signatureKey, out var existing))
				{
					// Conflict: same method signature from different interfaces
					// Prefer non-void return type (more informative for user)
					if (existing.IsVoid && !method.IsVoid)
					{
						methodsToRender[signatureKey] = method;
					}
					// Otherwise keep the first one (or the non-void one already stored)
				}
				else
				{
					methodsToRender[signatureKey] = method;
				}
			}

			// Render the selected methods
			foreach (var method in methodsToRender.Values)
			{
				RenderBaseClassMethod(w, method);
			}

			// Generate virtual protected properties for each interface property
			// When multiple interfaces have the same property name but different accessors
			// (e.g., IReadOnly.Name has getter only, IMutable.Name has get/set), we must pick one.
			// We prefer the version with MORE accessors (get/set > get-only or set-only).
			var propertiesToRender = new Dictionary<string, FlatPropertyModel>();

			foreach (var property in unit.Properties)
			{
				// Skip delegation targets (these are synthetic properties)
				if (property.DelegationTarget != null)
					continue;

				// Key by property name ONLY
				// C# does not allow overloading properties by return type or accessors
				var key = property.MemberName;

				if (propertiesToRender.TryGetValue(key, out var existing))
				{
					// Conflict: same property name from different interfaces
					// Prefer the version with MORE accessors
					var existingAccessorCount = (existing.HasGetter ? 1 : 0) + (existing.HasSetter ? 1 : 0);
					var newAccessorCount = (property.HasGetter ? 1 : 0) + (property.HasSetter ? 1 : 0);

					if (newAccessorCount > existingAccessorCount)
					{
						propertiesToRender[key] = property;
					}
					// If same accessor count, keep first (stable ordering)
				}
				else
				{
					propertiesToRender[key] = property;
				}
			}

			// Render the selected properties
			foreach (var property in propertiesToRender.Values)
			{
				RenderBaseClassProperty(w, property);
			}
		}

		// Close containing type wrappers for nested classes
		for (int i = 0; i < unit.ContainingTypes.Count; i++)
		{
			w.Line("}");
		}

		return w.ToString();
	}

	/// <summary>
	/// Gets a signature key for a method that only includes parameter types, not return type.
	/// Used for base class deduplication where C# doesn't allow overloading by return type.
	/// </summary>
	private static string GetParameterOnlySignatureKey(FlatMethodModel method)
	{
		if (method.Parameters.Count == 0)
			return $"{method.MethodName}_NoParams";

		var paramTypes = method.Parameters
			.Select(p => p.Type.Replace("global::", "").Replace(" ", ""))
			.ToArray();
		return $"{method.MethodName}_{string.Join("_", paramTypes)}";
	}

	/// <summary>
	/// Renders a single virtual protected method in the base class.
	/// Method name is suffixed with '_' to distinguish from interface method.
	/// Returns default! to allow compilation without override.
	/// </summary>
	private static void RenderBaseClassMethod(CodeWriter w, FlatMethodModel method)
	{
		var methodName = $"{method.MethodName}_";
		var returnType = method.IsVoid ? "void" : method.ReturnType;

		// Check if method has out parameters that need to be assigned
		var outParams = method.Parameters.Where(p => p.RefKind == Microsoft.CodeAnalysis.RefKind.Out).ToList();
		var hasOutParams = outParams.Count > 0;

		w.Line($"/// <summary>Override to provide default implementation for {method.DeclaringInterface}.{method.MethodName}.</summary>");

		if (hasOutParams)
		{
			// Methods with out parameters need a block body to assign all out params
			w.Line($"protected virtual {returnType} {methodName}({method.ParameterDeclarations})");
			using (w.Braces())
			{
				// Assign all out parameters to default
				foreach (var outParam in outParams)
				{
					w.Line($"{outParam.EscapedName} = default!;");
				}

				// Return default if non-void
				if (!method.IsVoid)
				{
					w.Line("return default!;");
				}
			}
		}
		else if (method.IsVoid)
		{
			w.Line($"protected virtual {returnType} {methodName}({method.ParameterDeclarations}) {{ }}");
		}
		else
		{
			w.Line($"protected virtual {returnType} {methodName}({method.ParameterDeclarations}) => default!;");
		}
		w.Line();
	}

	/// <summary>
	/// Renders a single virtual protected property in the base class.
	/// Property name is suffixed with '_' to distinguish from interface property.
	/// Returns default! to allow compilation without override.
	/// </summary>
	private static void RenderBaseClassProperty(CodeWriter w, FlatPropertyModel property)
	{
		var propertyName = $"{property.MemberName}_";
		var returnType = property.ReturnType;

		w.Line($"/// <summary>Override to provide default implementation for {property.DeclaringInterface}.{property.MemberName}.</summary>");

		if (property.HasGetter && property.HasSetter)
		{
			// Get/set property - full property syntax
			w.Line($"protected virtual {returnType} {propertyName} {{ get => default!; set {{ }} }}");
		}
		else if (property.HasGetter)
		{
			// Get-only property - expression-bodied
			w.Line($"protected virtual {returnType} {propertyName} => default!;");
		}
		else if (property.HasSetter)
		{
			// Set-only property - block syntax
			w.Line($"protected virtual {returnType} {propertyName} {{ set {{ }} }}");
		}
		w.Line();
	}

	#region Indexer Access Helpers

	/// <summary>
	/// Builds a map from indexer InterceptorName to the property access expression.
	/// For single-indexer groups: "Indexer"
	/// For multi-indexer groups: "Indexer.OfInt32", "Indexer.OfString", etc.
	/// </summary>
	private static Dictionary<string, string> BuildIndexerAccessMap(EquatableArray<FlatIndexerGroup> groups)
	{
		var map = new Dictionary<string, string>();

		foreach (var group in groups)
		{
			if (group.Indexers.Count == 1)
			{
				// Single indexer - direct access
				var indexer = group.Indexers.GetArray()![0];
				map[indexer.InterceptorName] = group.BaseName;
			}
			else
			{
				// Multiple indexers - container with OfXxx pattern
				foreach (var indexer in group.Indexers)
				{
					map[indexer.InterceptorName] = $"{group.BaseName}.Of{indexer.KeyTypeFriendlyName}";
				}
			}
		}

		return map;
	}

	#endregion

	#region Type Parameter Formatting

	private static string FormatTypeParameters(EquatableArray<TypeParameterModel> typeParameters)
	{
		if (typeParameters.Count == 0)
			return "";

		var names = string.Join(", ", typeParameters.Select(tp => tp.Name));
		return $"<{names}>";
	}

	private static string FormatConstraints(EquatableArray<TypeParameterModel> typeParameters)
	{
		if (typeParameters.Count == 0)
			return "";

		var clauses = typeParameters
			.Where(tp => !string.IsNullOrEmpty(tp.Constraints))
			.Select(tp => $" where {tp.Name} : {tp.Constraints}");

		return string.Join("", clauses);
	}

	#endregion

	#region Generic Method Interfaces

	private static void RenderGenericMethodInterfaces(CodeWriter w)
	{
		w.Line("/// <summary>Interface for tracking calls to generic methods.</summary>");
		using (w.Block("private interface IGenericMethodCallTracker"))
		{
			w.Line("int CallCount { get; }");
		}
		w.Line();

		w.Line("/// <summary>Interface for resetting state.</summary>");
		using (w.Block("private interface IResettable"))
		{
			w.Line("void Reset();");
		}
		w.Line();
	}

	#endregion

	#region Property Interceptor Class

	private static void RenderPropertyInterceptorClass(CodeWriter w, FlatPropertyModel prop, string className)
	{
		w.Line($"/// <summary>Tracks and configures behavior for {prop.MemberName}.</summary>");
		using (w.Block($"public sealed class {prop.InterceptorClassName}"))
		{
			if (prop.IsInitOnly)
			{
				RenderInitPropertyInterceptorContent(w, prop);
			}
			else
			{
				RenderRegularPropertyInterceptorContent(w, prop, className);
			}
		}
		w.Line();
	}

	private static void RenderInitPropertyInterceptorContent(CodeWriter w, FlatPropertyModel prop)
	{
		// Verifiable state
		w.Line("private bool _isVerifiable;");
		w.Line("private global::KnockOff.Called? _verifiableTimes;");
		w.Line("private bool _valueSet;");
		w.Line();

		w.Line("private " + prop.ReturnType + " _value = default!;");
		w.Line($"/// <summary>The configured value for {prop.MemberName}. Setting this marks the property as configured.</summary>");
		w.Line($"public {prop.ReturnType} Value");
		using (w.Braces())
		{
			w.Line("get => _value;");
			w.Line("set { _value = value; _valueSet = true; }");
		}
		w.Line();

		w.Line("private int _getCount;");
		w.Line("private int _setCount;");
		w.Line();

		w.Line("/// <summary>The value from the most recent setter call.</summary>");
		w.Line($"public {prop.NullableReturnType} LastSetValue {{ get; private set; }}");
		w.Line();

		w.Line("/// <summary>Records a getter access.</summary>");
		w.Line("public void RecordGet() => _getCount++;");
		w.Line();

		w.Line("/// <summary>Records a setter access.</summary>");
		w.Line($"public void RecordSet({prop.NullableReturnType} value) {{ _setCount++; LastSetValue = value; }}");
		w.Line();

		w.Line("/// <summary>Resets tracking state (counts, LastSetValue) but preserves configuration (Value) and verifiable marking.</summary>");
		w.Line("public void Reset() { _getCount = 0; _setCount = 0; LastSetValue = default; }");
		w.Line();

		// Verifiable methods (fluent)
		w.Line($"/// <summary>Marks this property for verification by Stub.Verify(). Returns this for fluent chaining.</summary>");
		w.Line($"public {prop.InterceptorClassName} Verifiable() {{ _isVerifiable = true; _verifiableTimes = null; return this; }}");
		w.Line();
		w.Line($"/// <summary>Marks this property for verification by Stub.Verify() with Called constraint. Returns this for fluent chaining.</summary>");
		w.Line($"public {prop.InterceptorClassName} Verifiable(global::KnockOff.Called times) {{ _isVerifiable = true; _verifiableTimes = times; return this; }}");
		w.Line();

		// Verify methods - throw on failure
		w.Line("/// <summary>Verifies the property was accessed at least once. Throws VerificationException if not.</summary>");
		w.Line("public void Verify() => Verify(global::KnockOff.Called.AtLeastOnce);");
		w.Line();

		w.Line("/// <summary>Verifies total access count satisfies the Called constraint. Throws VerificationException if not.</summary>");
		w.Line("public void Verify(global::KnockOff.Called times)");
		using (w.Braces())
		{
			w.Line("var totalCount = _getCount + _setCount;");
			w.Line("if (!times.Validate(totalCount))");
			w.Line($"\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"{prop.MemberName}\", times, totalCount));");
		}
		w.Line();

		// VerifyGet methods
		w.Line("/// <summary>Verifies the getter was accessed at least once. Throws VerificationException if not.</summary>");
		w.Line("public void VerifyGet() => VerifyGet(global::KnockOff.Called.AtLeastOnce);");
		w.Line();

		w.Line("/// <summary>Verifies getter access count satisfies the Called constraint. Throws VerificationException if not.</summary>");
		w.Line("public void VerifyGet(global::KnockOff.Called times)");
		using (w.Braces())
		{
			w.Line("if (!times.Validate(_getCount))");
			w.Line($"\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"{prop.MemberName} (get)\", times, _getCount));");
		}
		w.Line();

		// VerifySet methods
		w.Line("/// <summary>Verifies the setter was accessed at least once. Throws VerificationException if not.</summary>");
		w.Line("public void VerifySet() => VerifySet(global::KnockOff.Called.AtLeastOnce);");
		w.Line();

		w.Line("/// <summary>Verifies setter access count satisfies the Called constraint. Throws VerificationException if not.</summary>");
		w.Line("public void VerifySet(global::KnockOff.Called times)");
		using (w.Braces())
		{
			w.Line("if (!times.Validate(_setCount))");
			w.Line($"\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"{prop.MemberName} (set)\", times, _setCount));");
		}
		w.Line();

		// Internal verification support for stub-level Verify/VerifyAll
		w.Line("/// <summary>Whether this property was marked with Verifiable().</summary>");
		w.Line("internal bool IsVerifiable => _isVerifiable;");
		w.Line();

		w.Line("/// <summary>Whether this property has been configured (Value set).</summary>");
		w.Line("internal bool IsConfigured => _valueSet;");
		w.Line();

		w.Line("/// <summary>Checks verification for Stub.Verify() - only checks if marked verifiable.</summary>");
		w.Line($"internal global::KnockOff.VerificationFailure? CheckVerification()");
		using (w.Braces())
		{
			w.Line("if (!_isVerifiable) return null;");
			w.Line("var times = _verifiableTimes ?? global::KnockOff.Called.AtLeastOnce;");
			w.Line("var totalCount = _getCount + _setCount;");
			w.Line($"return times.Validate(totalCount) ? null : new global::KnockOff.VerificationFailure(\"{prop.MemberName}\", times, totalCount);");
		}
		w.Line();

		w.Line("/// <summary>Checks verification for Stub.VerifyAll() - checks if configured.</summary>");
		w.Line($"internal global::KnockOff.VerificationFailure? CheckVerificationAll()");
		using (w.Braces())
		{
			w.Line("if (!IsConfigured) return null;");
			w.Line("var totalCount = _getCount + _setCount;");
			w.Line($"return totalCount >= 1 ? null : new global::KnockOff.VerificationFailure(\"{prop.MemberName}\", global::KnockOff.Called.AtLeastOnce, totalCount);");
		}
	}

	private static void RenderRegularPropertyInterceptorContent(CodeWriter w, FlatPropertyModel prop, string className)
	{
		// Source field for Source(T) feature - uses declaring interface type
		w.Line($"/// <summary>Source object to delegate to when no Get/Set is configured.</summary>");
		w.Line($"internal {prop.DeclaringInterface}? _source;");
		w.Line();

		// Verifiable state
		w.Line("private bool _isVerifiable;");
		w.Line("private global::KnockOff.Called? _verifiableTimes;");
		w.Line("private bool _valueSet;");
		w.Line();

		if (prop.HasGetter)
		{
			w.Line("private int _getCount;");
			w.Line();

			w.Line("/// <summary>Callback invoked when the getter is accessed. If set, its return value is used.</summary>");
			w.Line($"public global::System.Func<{prop.ReturnType}>? Get {{ get; set; }}");
			w.Line();
		}

		if (prop.HasSetter)
		{
			w.Line("private int _setCount;");
			w.Line();

			w.Line("/// <summary>The value from the most recent setter call.</summary>");
			w.Line($"public {prop.NullableReturnType} LastSetValue {{ get; private set; }}");
			w.Line();

			w.Line("/// <summary>Callback invoked when the setter is accessed.</summary>");
			w.Line($"public global::System.Action<{prop.ReturnType}>? Set {{ get; set; }}");
			w.Line();
		}

		// Value property for backing storage - setting Value marks the property as configured
		w.Line("private " + prop.ReturnType + " _value" + GetDefaultValueSuffix(prop.DefaultExpression));
		w.Line("/// <summary>Value returned by getter when Get is not set. Setting this marks the property as configured.</summary>");
		w.Line($"public {prop.ReturnType} Value");
		using (w.Braces())
		{
			w.Line("get => _value;");
			w.Line("set { _value = value; _valueSet = true; }");
		}
		w.Line();

		if (prop.HasGetter)
		{
			w.Line("/// <summary>Records a getter access.</summary>");
			w.Line("public void RecordGet() => _getCount++;");
			w.Line();
		}

		if (prop.HasSetter)
		{
			w.Line("/// <summary>Records a setter access.</summary>");
			w.Line($"public void RecordSet({prop.NullableReturnType} value) {{ _setCount++; LastSetValue = value; }}");
			w.Line();
		}

		// Reset method - clears tracking state but preserves configuration (Get/Set/Value) and verifiable marking
		w.Line("/// <summary>Resets tracking state (counts, LastSetValue) but preserves configuration (Get, Set, Value) and verifiable marking.</summary>");
		var resetParts = new System.Collections.Generic.List<string>();
		if (prop.HasGetter) resetParts.Add("_getCount = 0;");
		if (prop.HasSetter) resetParts.Add("_setCount = 0; LastSetValue = default;");
		resetParts.Add("_source = null;");
		w.Line($"public void Reset() {{ {string.Join(" ", resetParts)} }}");
		w.Line();

		// Verifiable methods (fluent)
		w.Line($"/// <summary>Marks this property for verification by Stub.Verify(). Returns this for fluent chaining.</summary>");
		w.Line($"public {prop.InterceptorClassName} Verifiable() {{ _isVerifiable = true; _verifiableTimes = null; return this; }}");
		w.Line();
		w.Line($"/// <summary>Marks this property for verification by Stub.Verify() with Called constraint. Returns this for fluent chaining.</summary>");
		w.Line($"public {prop.InterceptorClassName} Verifiable(global::KnockOff.Called times) {{ _isVerifiable = true; _verifiableTimes = times; return this; }}");
		w.Line();

		// Build total count expression based on available accessors
		var totalCountExpr = prop.HasGetter && prop.HasSetter
			? "_getCount + _setCount"
			: (prop.HasGetter ? "_getCount" : "_setCount");

		// Verify methods - throw on failure
		w.Line("/// <summary>Verifies the property was accessed at least once. Throws VerificationException if not.</summary>");
		w.Line("public void Verify() => Verify(global::KnockOff.Called.AtLeastOnce);");
		w.Line();

		w.Line("/// <summary>Verifies total access count satisfies the Called constraint. Throws VerificationException if not.</summary>");
		w.Line("public void Verify(global::KnockOff.Called times)");
		using (w.Braces())
		{
			w.Line($"var totalCount = {totalCountExpr};");
			w.Line("if (!times.Validate(totalCount))");
			w.Line($"\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"{prop.MemberName}\", times, totalCount));");
		}
		w.Line();

		// VerifyGet methods
		if (prop.HasGetter)
		{
			w.Line("/// <summary>Verifies the getter was accessed at least once. Throws VerificationException if not.</summary>");
			w.Line("public void VerifyGet() => VerifyGet(global::KnockOff.Called.AtLeastOnce);");
			w.Line();

			w.Line("/// <summary>Verifies getter access count satisfies the Called constraint. Throws VerificationException if not.</summary>");
			w.Line("public void VerifyGet(global::KnockOff.Called times)");
			using (w.Braces())
			{
				w.Line("if (!times.Validate(_getCount))");
				w.Line($"\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"{prop.MemberName} (get)\", times, _getCount));");
			}
			w.Line();
		}

		// VerifySet methods
		if (prop.HasSetter)
		{
			w.Line("/// <summary>Verifies the setter was accessed at least once. Throws VerificationException if not.</summary>");
			w.Line("public void VerifySet() => VerifySet(global::KnockOff.Called.AtLeastOnce);");
			w.Line();

			w.Line("/// <summary>Verifies setter access count satisfies the Called constraint. Throws VerificationException if not.</summary>");
			w.Line("public void VerifySet(global::KnockOff.Called times)");
			using (w.Braces())
			{
				w.Line("if (!times.Validate(_setCount))");
				w.Line($"\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"{prop.MemberName} (set)\", times, _setCount));");
			}
			w.Line();
		}

		// Internal verification support for stub-level Verify/VerifyAll
		w.Line("/// <summary>Whether this property was marked with Verifiable().</summary>");
		w.Line("internal bool IsVerifiable => _isVerifiable;");
		w.Line();

		// IsConfigured - Value set OR Get/Set callback registered
		var isConfiguredParts = new System.Collections.Generic.List<string> { "_valueSet" };
		if (prop.HasGetter) isConfiguredParts.Add("Get != null");
		if (prop.HasSetter) isConfiguredParts.Add("Set != null");
		w.Line("/// <summary>Whether this property has been configured (Value set or callbacks registered).</summary>");
		w.Line($"internal bool IsConfigured => {string.Join(" || ", isConfiguredParts)};");
		w.Line();

		w.Line("/// <summary>Checks verification for Stub.Verify() - only checks if marked verifiable.</summary>");
		w.Line($"internal global::KnockOff.VerificationFailure? CheckVerification()");
		using (w.Braces())
		{
			w.Line("if (!_isVerifiable) return null;");
			w.Line("var times = _verifiableTimes ?? global::KnockOff.Called.AtLeastOnce;");
			w.Line($"var totalCount = {totalCountExpr};");
			w.Line($"return times.Validate(totalCount) ? null : new global::KnockOff.VerificationFailure(\"{prop.MemberName}\", times, totalCount);");
		}
		w.Line();

		w.Line("/// <summary>Checks verification for Stub.VerifyAll() - checks if configured.</summary>");
		w.Line($"internal global::KnockOff.VerificationFailure? CheckVerificationAll()");
		using (w.Braces())
		{
			w.Line("if (!IsConfigured) return null;");
			w.Line($"var totalCount = {totalCountExpr};");
			w.Line($"return totalCount >= 1 ? null : new global::KnockOff.VerificationFailure(\"{prop.MemberName}\", global::KnockOff.Called.AtLeastOnce, totalCount);");
		}
	}

	private static string GetDefaultValueSuffix(string defaultExpression)
	{
		// The DefaultExpression from the model contains the complete expression (e.g., "default!", "new List<int>()")
		// We need to convert it to an initializer format with " = " prefix and ";" suffix
		if (string.IsNullOrEmpty(defaultExpression) || defaultExpression == "default!")
			return " = default!;";

		// For NewInstance strategy, the expression will be like "new SomeType()"
		return $" = {defaultExpression};";
	}

