	#region Event Interceptor Class

	private static void RenderEventInterceptorClass(CodeWriter w, FlatEventModel evt)
	{
		w.Line($"/// <summary>Interceptor for {evt.EventName} event.</summary>");
		using (w.Block($"public sealed class {evt.InterceptorClassName}"))
		{
			// Backing field
			w.Line($"private {evt.DelegateType}? _handler;");
			w.Line();

			// Add/Remove tracking
			w.Line("private int _addCount;");
			w.Line("private int _removeCount;");
			w.Line();

			w.Line("/// <summary>Whether any handlers are subscribed.</summary>");
			w.Line("public bool HasSubscribers => _handler != null;");
			w.Line();

			// RecordAdd/RecordRemove
			w.Line($"/// <summary>Records an event subscription.</summary>");
			w.Line($"public void RecordAdd({evt.DelegateType}? value) {{ _addCount++; _handler = ({evt.DelegateType}?)global::System.Delegate.Combine(_handler, value); }}");
			w.Line();

			w.Line($"/// <summary>Records an event unsubscription.</summary>");
			w.Line($"public void RecordRemove({evt.DelegateType}? value) {{ _removeCount++; _handler = ({evt.DelegateType}?)global::System.Delegate.Remove(_handler, value); }}");
			w.Line();

			// Raise method
			RenderEventRaiseMethod(w, evt);

			// Reset - clears tracking state but preserves verifiable marking
			w.Line("/// <summary>Resets tracking state (counts, handler) but preserves verifiable marking.</summary>");
			w.Line("public void Reset() { _addCount = 0; _removeCount = 0; _handler = null; }");
			w.Line();

			// Verification API for events
			w.Line("private bool _isVerifiable;");
			w.Line("private global::KnockOff.Called? _verifiableTimes;");
			w.Line();

			w.Line("/// <summary>Verifies the event was subscribed to at least once.</summary>");
			w.Line("public void VerifyAdd() => VerifyAdd(global::KnockOff.Called.AtLeastOnce);");
			w.Line();

			w.Line("/// <summary>Verifies the event subscription count matches the Called constraint.</summary>");
			w.Line("public void VerifyAdd(global::KnockOff.Called times)");
			using (w.Braces())
			{
				w.Line("if (!times.Validate(_addCount))");
				w.Line($"\tthrow new global::KnockOff.VerificationException($\"Event '{evt.EventName}' add verification failed: expected {{times}}, but was called {{_addCount}} time(s).\");");
			}
			w.Line();

			w.Line("/// <summary>Verifies the event was unsubscribed at least once.</summary>");
			w.Line("public void VerifyRemove() => VerifyRemove(global::KnockOff.Called.AtLeastOnce);");
			w.Line();

			w.Line("/// <summary>Verifies the event unsubscription count matches the Called constraint.</summary>");
			w.Line("public void VerifyRemove(global::KnockOff.Called times)");
			using (w.Braces())
			{
				w.Line("if (!times.Validate(_removeCount))");
				w.Line($"\tthrow new global::KnockOff.VerificationException($\"Event '{evt.EventName}' remove verification failed: expected {{times}}, but was called {{_removeCount}} time(s).\");");
			}
			w.Line();

			w.Line("/// <summary>Verifies the event was accessed (add or remove) at least once.</summary>");
			w.Line("public void Verify() => Verify(global::KnockOff.Called.AtLeastOnce);");
			w.Line();

			w.Line("/// <summary>Verifies the total event access count matches the Called constraint.</summary>");
			w.Line("public void Verify(global::KnockOff.Called times)");
			using (w.Braces())
			{
				w.Line("var totalCount = _addCount + _removeCount;");
				w.Line("if (!times.Validate(totalCount))");
				w.Line($"\tthrow new global::KnockOff.VerificationException($\"Event '{evt.EventName}' verification failed: expected {{times}}, but was called {{totalCount}} time(s).\");");
			}
			w.Line();

			w.Line("/// <summary>Marks this event for verification by Stub.Verify(). Returns this for fluent chaining.</summary>");
			w.Line($"public {evt.InterceptorClassName} Verifiable()");
			using (w.Braces())
			{
				w.Line("_isVerifiable = true;");
				w.Line("_verifiableTimes = global::KnockOff.Called.AtLeastOnce;");
				w.Line("return this;");
			}
			w.Line();

			w.Line("/// <summary>Marks this event for verification by Stub.Verify() with Called constraint. Returns this for fluent chaining.</summary>");
			w.Line($"public {evt.InterceptorClassName} Verifiable(global::KnockOff.Called times)");
			using (w.Braces())
			{
				w.Line("_isVerifiable = true;");
				w.Line("_verifiableTimes = times;");
				w.Line("return this;");
			}
			w.Line();

			// Internal verification methods for stub-level Verify()/VerifyAll()
			w.Line("internal bool IsVerifiable => _isVerifiable;");
			w.Line("internal bool IsConfigured => _handler != null;");
			w.Line();

			w.Line("/// <summary>Checks verification for Stub.Verify() - only verifiable items.</summary>");
			w.Line("internal global::KnockOff.VerificationFailure? CheckVerification()");
			using (w.Braces())
			{
				w.Line("if (!_isVerifiable) return null;");
				w.Line("var times = _verifiableTimes ?? global::KnockOff.Called.AtLeastOnce;");
				w.Line("var totalCount = _addCount + _removeCount;");
				w.Line("if (!times.Validate(totalCount))");
				w.Line($"\treturn new global::KnockOff.VerificationFailure(\"{evt.EventName}\", times, totalCount);");
				w.Line("return null;");
			}
			w.Line();

			w.Line("/// <summary>Checks verification for Stub.VerifyAll() - all configured items.</summary>");
			w.Line("internal global::KnockOff.VerificationFailure? CheckVerificationAll()");
			using (w.Braces())
			{
				w.Line("if (!IsConfigured && !_isVerifiable) return null;");
				w.Line("var times = _verifiableTimes ?? global::KnockOff.Called.AtLeastOnce;");
				w.Line("var totalCount = _addCount + _removeCount;");
				w.Line("if (!times.Validate(totalCount))");
				w.Line($"\treturn new global::KnockOff.VerificationFailure(\"{evt.EventName}\", times, totalCount);");
				w.Line("return null;");
			}
		}
		w.Line();
	}

	private static void RenderEventRaiseMethod(CodeWriter w, FlatEventModel evt)
	{
		if (evt.RaiseReturnsValue)
		{
			// Func-style delegate
			w.Line("/// <summary>Raises the event with the specified arguments and returns the result.</summary>");
			if (string.IsNullOrEmpty(evt.RaiseParameters))
			{
				w.Line($"public {evt.RaiseReturnType} Raise() => _handler != null ? _handler.Invoke() : default!;");
			}
			else
			{
				w.Line($"public {evt.RaiseReturnType} Raise({evt.RaiseParameters}) => _handler != null ? _handler.Invoke({evt.RaiseArguments}) : default!;");
			}
		}
		else if (evt.UsesDynamicInvoke)
		{
			// Custom delegate - use DynamicInvoke
			if (string.IsNullOrEmpty(evt.RaiseParameters))
			{
				w.Line("/// <summary>Raises the event.</summary>");
				w.Line("public void Raise() => (_handler as global::System.Action)?.Invoke();");
			}
			else
			{
				w.Line("/// <summary>Invokes the handler if subscribed.</summary>");
				w.Line($"public void Raise({evt.RaiseParameters}) => _handler?.DynamicInvoke({evt.RaiseArguments});");
			}
		}
		else
		{
			// Standard Action/EventHandler
			if (string.IsNullOrEmpty(evt.RaiseParameters))
			{
				w.Line("/// <summary>Raises the event.</summary>");
				w.Line("public void Raise() => _handler?.Invoke();");
			}
			else
			{
				w.Line("/// <summary>Raises the event with the specified arguments.</summary>");
				w.Line($"public void Raise({evt.RaiseParameters}) => _handler?.Invoke({evt.RaiseArguments});");
			}
		}
		w.Line();
	}

