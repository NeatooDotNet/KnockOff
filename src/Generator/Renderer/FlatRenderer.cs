	#region Standard Members

	private static void RenderStandardMembers(CodeWriter w, FlatGenerationUnit unit)
	{
		// Strict mode property with configurable default
		var strictDefault = unit.Strict ? "true" : "false";
		w.Line("/// <summary>When true, throws StubException for unconfigured member access.</summary>");
		w.Line($"public bool Strict {{ get; set; }} = {strictDefault};");
		w.Line();

		// Object accessor - returns the first interface type
		var typeParams = FormatTypeParameters(unit.TypeParameters);
		var primaryInterface = unit.InterfaceList.Count > 0 ? unit.InterfaceList.GetArray()![0] : $"{unit.ClassName}{typeParams}";
		w.Line($"/// <summary>The {primaryInterface} instance. Use for passing to code expecting the interface.</summary>");
		w.Line($"public {primaryInterface} Object => this;");
		w.Line();

		// Verify and VerifyAll methods (if there are any verifiable members)
		// Must check all member types: methods, stub overrides, properties, events
		// NOTE: Indexers excluded - there's a separate bug where indexer container accessor paths are wrong
		// TODO: Fix indexer verification accessor paths (see IndexerGroups vs individual Indexers)
		if (unit.MethodGroups.Count > 0
			|| unit.StubOverrideGroups.Count > 0
			|| unit.Properties.Count > 0
			|| unit.Events.Count > 0)
		{
			RenderVerifyMethods(w, unit);
		}

		// SmartDefault helper (only if there are generic methods)
		if (unit.HasGenericMethods)
		{
			RenderSmartDefaultMethod(w);
		}
	}

	private static void RenderVerifyMethods(CodeWriter w, FlatGenerationUnit unit)
	{
		// Get unique interceptor names for methods (method groups define the interceptor names)
		var methodInterceptorNames = unit.MethodGroups
			.Select(g => g.InterceptorName)
			.Distinct()
			.ToList();

		// Get unique user-defined method interceptor names (tracking-only, always configured)
		var stubOverrideInterceptorNames = unit.StubOverrideGroups
			.Select(g => g.InterceptorName)
			.Distinct()
			.ToList();

		// Get unique property interceptor names
		var propertyInterceptorNames = unit.Properties
			.Select(p => p.InterceptorName)
			.Distinct()
			.ToList();

		// Get unique indexer interceptor names
		var indexerInterceptorNames = unit.Indexers
			.Select(i => i.InterceptorName)
			.Distinct()
			.ToList();

		// Get unique event interceptor names
		var eventInterceptorNames = unit.Events
			.Select(e => e.InterceptorName)
			.Distinct()
			.ToList();

		// Verify method - checks only .Verifiable() items, throws if any fail
		w.Line("/// <summary>Verifies all members marked with .Verifiable() were invoked as expected. Throws VerificationException with all failures if any fail.</summary>");
		using (w.Block("public void Verify()"))
		{
			w.Line("var failures = new global::System.Collections.Generic.List<global::KnockOff.VerificationFailure>();");
			w.Line();

			// Check verifiable method interceptors
			foreach (var name in methodInterceptorNames)
			{
				w.Line($"if ({name}.CheckVerification() is {{ }} {name.ToLowerInvariant()}Failure) failures.Add({name.ToLowerInvariant()}Failure);");
			}

			// Check verifiable property interceptors
			foreach (var name in propertyInterceptorNames)
			{
				w.Line($"if ({name}.CheckVerification() is {{ }} {name.ToLowerInvariant()}Failure) failures.Add({name.ToLowerInvariant()}Failure);");
			}

			// Check verifiable indexer interceptors
			foreach (var name in indexerInterceptorNames)
			{
				w.Line($"if ({name}.CheckVerification() is {{ }} {name.ToLowerInvariant()}Failure) failures.Add({name.ToLowerInvariant()}Failure);");
			}

			// Check verifiable event interceptors
			foreach (var name in eventInterceptorNames)
			{
				w.Line($"if ({name}.CheckVerification() is {{ }} {name.ToLowerInvariant()}Failure) failures.Add({name.ToLowerInvariant()}Failure);");
			}

			// Check verifiable user-defined method interceptors
			foreach (var name in stubOverrideInterceptorNames)
			{
				w.Line($"if ({name}.CheckVerification() is {{ }} {name.ToLowerInvariant()}Failure) failures.Add({name.ToLowerInvariant()}Failure);");
			}

			w.Line();
			w.Line("if (failures.Count > 0)");
			w.Line("\tthrow new global::KnockOff.VerificationException(failures);");
		}
		w.Line();

		// VerifyAll method - checks ALL configured members, throws if any fail
		// NOTE: User-defined methods are NOT included in VerifyAll because they are always "configured"
		w.Line("/// <summary>Verifies ALL configured members were invoked at least once. Throws VerificationException with all failures if any fail.</summary>");
		using (w.Block("public void VerifyAll()"))
		{
			w.Line("var failures = new global::System.Collections.Generic.List<global::KnockOff.VerificationFailure>();");
			w.Line();

			// Check all configured method interceptors
			foreach (var name in methodInterceptorNames)
			{
				w.Line($"if ({name}.CheckVerificationAll() is {{ }} {name.ToLowerInvariant()}Failure) failures.Add({name.ToLowerInvariant()}Failure);");
			}

			// Check all configured property interceptors
			foreach (var name in propertyInterceptorNames)
			{
				w.Line($"if ({name}.CheckVerificationAll() is {{ }} {name.ToLowerInvariant()}Failure) failures.Add({name.ToLowerInvariant()}Failure);");
			}

			// Check all configured indexer interceptors
			foreach (var name in indexerInterceptorNames)
			{
				w.Line($"if ({name}.CheckVerificationAll() is {{ }} {name.ToLowerInvariant()}Failure) failures.Add({name.ToLowerInvariant()}Failure);");
			}

			// Check all configured event interceptors
			foreach (var name in eventInterceptorNames)
			{
				w.Line($"if ({name}.CheckVerificationAll() is {{ }} {name.ToLowerInvariant()}Failure) failures.Add({name.ToLowerInvariant()}Failure);");
			}

			w.Line();
			w.Line("if (failures.Count > 0)");
			w.Line("\tthrow new global::KnockOff.VerificationException(failures);");
		}
		w.Line();
	}

	private static void RenderSmartDefaultMethod(CodeWriter w)
	{
		w.Line("/// <summary>Gets a smart default value for a generic type at runtime.</summary>");
		using (w.Block("private static T SmartDefault<T>(string methodName)"))
		{
			w.Line("var type = typeof(T);");
			w.Line();
			w.Line("// Value types -> default(T)");
			w.Line("if (type.IsValueType)");
			w.Line("\treturn default!;");
			w.Line();
			w.Line("// Check for parameterless constructor");
			w.Line("var ctor = type.GetConstructor(");
			w.Line("\tSystem.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Instance,");
			w.Line("\tnull, System.Type.EmptyTypes, null);");
			w.Line();
			w.Line("if (ctor != null)");
			w.Line("\treturn (T)ctor.Invoke(null);");
			w.Line();
			w.Line("throw new global::System.InvalidOperationException(");
			w.Line("\t$\"No implementation provided for {methodName}<{type.Name}>. \" +");
			w.Line("\t$\"Set the handler's Return or Call.\");");
		}
		w.Line();
	}

