	#region Property Implementation

	private static void RenderPropertyImplementation(CodeWriter w, FlatPropertyModel prop)
	{
		// Handle property delegation (e.g., IProperty.Value (object) delegates to IProperty<T>.Value (T))
		if (prop.DelegationTarget != null && prop.DelegationTargetInterface != null)
		{
			RenderPropertyDelegation(w, prop);
			return;
		}

		// User-defined properties with base class pattern: record access, check Get/Set, then delegate to virtual property
		if (prop.HasStubOverride)
		{
			RenderPropertyStubOverrideImplementation(w, prop);
			return;
		}

		w.Line($"{prop.RefReturnPrefix}{prop.ReturnType} {prop.DeclaringInterface}.{prop.MemberName}");
		using (w.Braces())
		{
			if (prop.IsRefReturn)
			{
				// Ref return properties are always get-only (C# constraint)
				w.Line("get");
				using (w.Braces())
				{
					w.Line($"{prop.InterceptorName}.InvokeRefGet(Strict);");
					w.Line($"return ref {prop.InterceptorName}._refReturnBacking;");
				}
			}
			else if (prop.IsInitOnly)
			{
				// Init-only: use InvokeGet for getter, but init setter records and sets value via SetValue
				w.Line($"get => {prop.InterceptorName}.InvokeGet(Strict);");
				w.Line($"init {{ {prop.InterceptorName}.RecordSet(value); {prop.InterceptorName}.SetValue(value); }}");
			}
			else
			{
				// Regular properties: use InvokeGet/InvokeSet which handle the priority chain
				if (prop.HasGetter)
				{
					w.Line($"get => {prop.InterceptorName}.InvokeGet(Strict);");
				}

				if (prop.HasSetter)
				{
					if (prop.SetterPragmaDisable != null)
						w.Append(prop.SetterPragmaDisable);
					w.Line($"set => {prop.InterceptorName}.InvokeSet(Strict, value);");
					if (prop.SetterPragmaRestore != null)
						w.Line(prop.SetterPragmaRestore);
				}
			}
		}
		w.Line();
	}

	/// <summary>
	/// Renders the explicit interface implementation for a property with stub override (base class pattern).
	/// Priority chain: Get/Set > Stub override (virtual property with _ suffix).
	/// Unlike properties without stub override, this does NOT fall through to Strict/Default.
	/// </summary>
	private static void RenderPropertyStubOverrideImplementation(CodeWriter w, FlatPropertyModel prop)
	{
		w.Line($"{prop.ReturnType} {prop.DeclaringInterface}.{prop.MemberName}");
		using (w.Braces())
		{
			if (prop.HasGetter)
			{
				w.Line("get");
				using (w.Braces())
				{
					// Get supersedes stub override (InvokeGetCallback tracks internally)
					w.Line($"if ({prop.InterceptorName}.HasGet) return {prop.InterceptorName}.InvokeGetCallback();");
					// Record access only for stub override path (to avoid double counting)
					w.Line($"{prop.InterceptorName}.RecordGet();");
					// Stub override (virtual property with _ suffix)
					w.Line($"return {prop.MemberName}_;");
				}
			}

			if (prop.HasSetter)
			{
				if (prop.SetterPragmaDisable != null)
					w.Append(prop.SetterPragmaDisable);
				w.Line("set");
				using (w.Braces())
				{
					// Set supersedes stub override (InvokeSetCallback tracks internally)
					w.Line($"if ({prop.InterceptorName}.HasSet) {{ {prop.InterceptorName}.InvokeSetCallback(value); return; }}");
					// Record access only for stub override path (to avoid double counting)
					w.Line($"{prop.InterceptorName}.RecordSet(value);");
					// Stub override (virtual property with _ suffix)
					w.Line($"{prop.MemberName}_ = value;");
				}
				if (prop.SetterPragmaRestore != null)
					w.Line(prop.SetterPragmaRestore);
			}
		}
		w.Line();
	}

	private static void RenderPropertyDelegation(CodeWriter w, FlatPropertyModel prop)
	{
		var target = prop.DelegationTarget!;
		var targetInterface = prop.DelegationTargetInterface!;

		w.Line($"{prop.ReturnType} {prop.DeclaringInterface}.{prop.MemberName}");
		using (w.Braces())
		{
			if (prop.HasGetter)
			{
				// Cast the typed value to object (or the base return type)
				w.Line($"get => (({targetInterface})this).{target.Name}!;");
			}

			if (prop.HasSetter)
			{
				// Cast the object value to the typed type
				w.Line($"set => (({targetInterface})this).{target.Name} = ({target.ReturnType.TrimEnd('?')})value!;");
			}
		}
		w.Line();
	}

	#endregion

	#region Indexer Implementation

	private static void RenderIndexerImplementation(CodeWriter w, FlatIndexerModel indexer, Dictionary<string, string> indexerAccessMap)
	{
		// Get the correct access expression (e.g., "Indexer" or "Indexer.OfInt32")
		var accessExpr = indexerAccessMap.TryGetValue(indexer.InterceptorName, out var mapped)
			? mapped
			: indexer.InterceptorName;

		w.Line($"{indexer.RefReturnPrefix}{indexer.ReturnType} {indexer.DeclaringInterface}.this[{indexer.KeyType} {indexer.KeyParamName}]");
		using (w.Braces())
		{
			if (indexer.IsRefReturn)
			{
				// Ref return indexers are always get-only (C# constraint)
				w.Line("get");
				using (w.Braces())
				{
					w.Line($"{accessExpr}.InvokeRefGet(Strict, {indexer.KeyParamName});");
					w.Line($"return ref {accessExpr}._refReturnBacking;");
				}
			}
			else
			{
				// Use InvokeGet/InvokeSet which handle the priority chain
				if (indexer.HasGetter)
				{
					w.Line($"get => {accessExpr}.InvokeGet(Strict, {indexer.KeyParamName});");
				}

				if (indexer.HasSetter)
				{
					w.Line($"set => {accessExpr}.InvokeSet(Strict, {indexer.KeyParamName}, value);");
				}
			}
		}
		w.Line();
	}

