#nullable enable
using System;
using System.Collections.Generic;
using System.Linq;
using KnockOff;
using KnockOff.Builder;
using KnockOff.Model.Inline;
using KnockOff.Model.Shared;
using KnockOff.Model.StandaloneClass;
using KnockOff.Renderer.Shared;

namespace KnockOff.Renderer;

/// <summary>
/// Renders StandaloneClassGenerationUnit to source code.
/// Follows the same wrapper + nested Impl pattern as ClassRenderer,
/// but generates a partial class completion for the user's class (not nested in Stubs).
/// </summary>
internal static class StandaloneClassRenderer
{
    public static string Render(StandaloneClassGenerationUnit unit)
    {
        var w = new CodeWriter();

        w.Line("// <auto-generated/>");
        w.Line("#nullable enable");
        w.Line();

        // Namespace
        if (!string.IsNullOrEmpty(unit.Namespace))
        {
            w.Line($"namespace {unit.Namespace};");
            w.Line();
        }

        // Open containing type wrappers for nested classes
        foreach (var containingType in unit.ContainingTypes)
        {
            var accessMod = string.IsNullOrEmpty(containingType.AccessModifier)
                ? ""
                : containingType.AccessModifier + " ";
            w.Line($"{accessMod}partial {containingType.Keyword} {containingType.Name}");
            w.Line("{");
        }

        // Determine indentation for nested class context
        var baseIndent = unit.ContainingTypes.Count;
        var indent = new string('\t', baseIndent);
        var indent1 = indent + "\t";
        var indent2 = indent + "\t\t";
        var indent3 = indent + "\t\t\t";
        var indent4 = indent + "\t\t\t\t";

        var typeParamList = FormatTypeParameters(unit.TypeParameters);
        var constraintClauses = FormatConstraints(unit.TypeParameters);

        // Render interceptor classes (same as inline class stubs)
        foreach (var prop in unit.Properties)
        {
            var unifiedModel = ToUnifiedPropertyModel(prop);
            var options = new PropertyInterceptorRenderOptions(
                BaseIndent: baseIndent,
                IncludeStrictParameter: true,
                StrictAccessExpression: "strict",
                InterceptorTypeParameters: prop.TypeParameterList,
                InterceptorConstraints: prop.ConstraintClauses);
            w.SetIndent(baseIndent);
            PropertyInterceptorRenderer.RenderInterceptorClass(w, unifiedModel, options);
        }

        foreach (var indexer in unit.Indexers)
        {
            var unifiedModel = ToUnifiedIndexerModel(indexer);
            var options = new IndexerInterceptorRenderOptions(
                BaseIndent: baseIndent,
                IncludeStrictParameter: true,
                StrictAccessExpression: "strict",
                InterceptorTypeParameters: indexer.TypeParameterList,
                InterceptorConstraints: indexer.ConstraintClauses);
            w.SetIndent(baseIndent);
            IndexerInterceptorRenderer.RenderInterceptorClass(w, unifiedModel, options);
        }

        // Use shared MethodInterceptorRenderer for method interceptors
        foreach (var method in unit.Methods)
        {
            // Check if any signature in this interceptor has a user method override
            var hasUserMethod = !string.IsNullOrEmpty(method.UserMethodName) ||
                method.Overloads.Any(o => !string.IsNullOrEmpty(o.UserMethodName));
            var options = new InterceptorRenderOptions(
                BaseIndent: baseIndent,
                IncludeStrictParameter: true,
                StrictAccessExpression: "strict",
                InterceptorTypeParameters: typeParamList,
                InterceptorConstraints: constraintClauses,
                UserMethodFallback: hasUserMethod,
                StubTypeName: hasUserMethod ? $"{unit.ClassName}{typeParamList}" : null);
            w.SetIndent(baseIndent);
            MethodInterceptorRenderer.RenderInterceptorClass(w, method, options);
        }

        foreach (var evt in unit.Events)
        {
            RenderEventInterceptorClass(w, evt, unit.ClassName, indent);
        }

        // Render the wrapper partial class (user's class)
        // Extends the generated base class for user property overrides
        var baseClassName = $"{unit.ClassName}Base{typeParamList}";
        w.Line($"{indent}/// <summary>Generated completion for {unit.ClassName} stub. Provides interceptors and .Object property.</summary>");
        w.Line($"{indent}partial class {unit.ClassName}{typeParamList} : {baseClassName}, global::KnockOff.IKnockOffStub{constraintClauses}");
        w.Line($"{indent}{{");

        // Strict property
        w.Line($"{indent1}/// <summary>When true, unconfigured method calls throw StubException instead of returning default.</summary>");
        w.Line($"{indent1}public bool Strict {{ get; set; }}");
        w.Line();

        // Interceptor properties
        foreach (var interceptorProp in unit.InterceptorProperties)
        {
            w.Line($"{indent1}/// <summary>{interceptorProp.Description}</summary>");
            w.Line($"{indent1}public {interceptorProp.InterceptorTypeName} {interceptorProp.PropertyName} {{ get; }} = new();");
        }
        w.Line();

        // .Object property
        w.Line($"{indent1}/// <summary>The {ExtractSimpleTypeName(unit.TargetClassName)} instance. Pass this to code expecting the target class.</summary>");
        w.Line($"{indent1}public {unit.TargetClassForInheritance} Object {{ get; }}");
        w.Line();

        // Constructors
        foreach (var ctor in unit.Constructors)
        {
            RenderWrapperConstructor(w, ctor, unit.ClassName, typeParamList, indent1);
        }

        // ResetInterceptors method
        w.Line($"{indent1}/// <summary>Resets all interceptor state.</summary>");
        w.Line($"{indent1}public void ResetInterceptors()");
        w.Line($"{indent1}{{");
        foreach (var resetStmt in unit.ResetStatements)
        {
            w.Line($"{indent2}{resetStmt}");
        }
        w.Line($"{indent1}}}");
        w.Line();

        // Verify and VerifyAll methods
        RenderVerifyMethods(w, unit, indent1, indent2);

        // Internal forwarding methods for user method overrides
        // Interceptor classes are top-level (not nested), so they cannot access
        // protected virtual methods on the base class. These internal forwarders
        // bridge the gap: interceptor calls stub.__UserMethod_X() which forwards
        // to the protected Execute_() method.
        RenderUserMethodForwarders(w, unit, indent1);

        // Nested Impl class
        RenderImplClass(w, unit, indent1, indent2, indent3, indent4);

        w.Line($"{indent}}}");

        // Close containing type wrappers for nested classes
        for (int i = 0; i < unit.ContainingTypes.Count; i++)
        {
            w.Line("}");
        }

        return w.ToString();
    }

    /// <summary>
    /// Renders the base class file for standalone class stubs.
    /// Contains virtual protected properties for each target class property, suffixed with '_'.
    /// Users can override these properties to provide default implementations.
    /// </summary>
    public static string RenderBaseClass(StandaloneClassGenerationUnit unit)
    {
        var w = new CodeWriter();

        w.Line("// <auto-generated/>");
        w.Line("#nullable enable");
        w.Line();

        // Namespace
        if (!string.IsNullOrEmpty(unit.Namespace))
        {
            w.Line($"namespace {unit.Namespace};");
            w.Line();
        }

        // Open containing type wrappers for nested classes
        foreach (var containingType in unit.ContainingTypes)
        {
            var accessMod = string.IsNullOrEmpty(containingType.AccessModifier)
                ? ""
                : containingType.AccessModifier + " ";
            w.Line($"{accessMod}partial {containingType.Keyword} {containingType.Name}");
            w.Line("{");
        }

        // Base class declaration with type parameters and constraints
        var typeParams = FormatTypeParameters(unit.TypeParameters);
        var constraints = FormatConstraints(unit.TypeParameters);

        using (w.Block($"public class {unit.ClassName}Base{typeParams}{constraints}"))
        {
            // Generate virtual protected properties for each target class property
            foreach (var property in unit.BaseClassProperties)
            {
                RenderBaseClassProperty(w, property);
            }

            // Generate virtual protected methods for each target class method
            foreach (var method in unit.BaseClassMethods)
            {
                RenderBaseClassMethod(w, method);
            }
        }

        // Close containing type wrappers for nested classes
        for (int i = 0; i < unit.ContainingTypes.Count; i++)
        {
            w.Line("}");
        }

        return w.ToString();
    }

    /// <summary>
    /// Renders a single virtual protected method in the base class.
    /// Method name is suffixed with '_' to distinguish from target class method.
    /// Void methods have empty body; non-void methods return default!.
    /// </summary>
    private static void RenderBaseClassMethod(CodeWriter w, BaseClassMethodModel method)
    {
        var methodName = $"{method.MethodName}_";
        var returnType = method.ReturnType;

        w.Line($"/// <summary>Override to provide default implementation for {method.TargetMemberDescription}.</summary>");

        if (method.IsVoid)
        {
            // Void method - empty body
            if (string.IsNullOrEmpty(method.ParameterDeclarations))
                w.Line($"protected virtual void {methodName}() {{ }}");
            else
                w.Line($"protected virtual void {methodName}({method.ParameterDeclarations}) {{ }}");
        }
        else
        {
            // Non-void method - expression-bodied returning default!
            if (string.IsNullOrEmpty(method.ParameterDeclarations))
                w.Line($"protected virtual {returnType} {methodName}() => default!;");
            else
                w.Line($"protected virtual {returnType} {methodName}({method.ParameterDeclarations}) => default!;");
        }
        w.Line();
    }

    /// <summary>
    /// Renders a single virtual protected property in the base class.
    /// Property name is suffixed with '_' to distinguish from target class property.
    /// Returns default! to allow compilation without override.
    /// </summary>
    private static void RenderBaseClassProperty(CodeWriter w, BaseClassPropertyModel property)
    {
        var propertyName = $"{property.PropertyName}_";
        var returnType = property.ReturnType;

        w.Line($"/// <summary>Override to provide default implementation for {property.TargetMemberDescription}.</summary>");

        if (property.HasGetter && property.HasSetter)
        {
            // Get/set property - full property syntax
            w.Line($"protected virtual {returnType} {propertyName} {{ get => default!; set {{ }} }}");
        }
        else if (property.HasGetter)
        {
            // Get-only property - expression-bodied
            w.Line($"protected virtual {returnType} {propertyName} => default!;");
        }
        else if (property.HasSetter)
        {
            // Set-only property - block syntax
            w.Line($"protected virtual {returnType} {propertyName} {{ set {{ }} }}");
        }
        w.Line();
    }

    #region Event Interceptor Rendering

    private static void RenderEventInterceptorClass(CodeWriter w, InlineClassEventModel evt, string stubClassName, string indent)
    {
        var indent1 = indent + "\t";

        w.Line($"{indent}/// <summary>Interceptor for {stubClassName}.{evt.EventName}.</summary>");
        w.Line($"{indent}public sealed class {evt.InterceptorClassName}{evt.TypeParameterList}{evt.ConstraintClauses}");
        w.Line($"{indent}{{");

        w.Line($"{indent1}/// <summary>Number of times the event was subscribed to.</summary>");
        w.Line($"{indent1}private int _addCount;");
        w.Line();
        w.Line($"{indent1}/// <summary>Number of times the event was unsubscribed from.</summary>");
        w.Line($"{indent1}private int _removeCount;");
        w.Line();
        w.Line($"{indent1}/// <summary>The backing delegate for raising the event.</summary>");
        w.Line($"{indent1}public {evt.DelegateType}? Handler {{ get; private set; }}");
        w.Line();
        w.Line($"{indent1}/// <summary>Records an event subscription.</summary>");
        w.Line($"{indent1}public void RecordAdd({evt.DelegateType}? handler) {{ _addCount++; Handler = ({evt.DelegateType}?)global::System.Delegate.Combine(Handler, handler); }}");
        w.Line();
        w.Line($"{indent1}/// <summary>Records an event unsubscription.</summary>");
        w.Line($"{indent1}public void RecordRemove({evt.DelegateType}? handler) {{ _removeCount++; Handler = ({evt.DelegateType}?)global::System.Delegate.Remove(Handler, handler); }}");
        w.Line();
        w.Line($"{indent1}/// <summary>Resets tracking state (counts, Handler) but preserves verifiable marking.</summary>");
        w.Line($"{indent1}public void Reset() {{ _addCount = 0; _removeCount = 0; Handler = null; }}");
        w.Line();

        // Verification API
        w.Line($"{indent1}private bool _isVerifiable;");
        w.Line($"{indent1}private global::KnockOff.Times? _verifiableTimes;");
        w.Line();

        w.Line($"{indent1}/// <summary>Verifies the event was subscribed to at least once.</summary>");
        w.Line($"{indent1}public void VerifyAdd() => VerifyAdd(global::KnockOff.Times.AtLeastOnce);");
        w.Line();

        w.Line($"{indent1}/// <summary>Verifies the event subscription count matches the Times constraint.</summary>");
        w.Line($"{indent1}public void VerifyAdd(global::KnockOff.Times times)");
        w.Line($"{indent1}{{");
        w.Line($"{indent1}\tif (!times.Validate(_addCount))");
        w.Line($"{indent1}\t\tthrow new global::KnockOff.VerificationException($\"Event '{evt.EventName}' add verification failed: expected {{times}}, but was called {{_addCount}} time(s).\");");
        w.Line($"{indent1}}}");
        w.Line();

        w.Line($"{indent1}/// <summary>Verifies the event was unsubscribed at least once.</summary>");
        w.Line($"{indent1}public void VerifyRemove() => VerifyRemove(global::KnockOff.Times.AtLeastOnce);");
        w.Line();

        w.Line($"{indent1}/// <summary>Verifies the event unsubscription count matches the Times constraint.</summary>");
        w.Line($"{indent1}public void VerifyRemove(global::KnockOff.Times times)");
        w.Line($"{indent1}{{");
        w.Line($"{indent1}\tif (!times.Validate(_removeCount))");
        w.Line($"{indent1}\t\tthrow new global::KnockOff.VerificationException($\"Event '{evt.EventName}' remove verification failed: expected {{times}}, but was called {{_removeCount}} time(s).\");");
        w.Line($"{indent1}}}");
        w.Line();

        w.Line($"{indent1}/// <summary>Verifies the event was accessed (add or remove) at least once.</summary>");
        w.Line($"{indent1}public void Verify() => Verify(global::KnockOff.Times.AtLeastOnce);");
        w.Line();

        w.Line($"{indent1}/// <summary>Verifies the total event access count matches the Times constraint.</summary>");
        w.Line($"{indent1}public void Verify(global::KnockOff.Times times)");
        w.Line($"{indent1}{{");
        w.Line($"{indent1}\tvar totalCount = _addCount + _removeCount;");
        w.Line($"{indent1}\tif (!times.Validate(totalCount))");
        w.Line($"{indent1}\t\tthrow new global::KnockOff.VerificationException($\"Event '{evt.EventName}' verification failed: expected {{times}}, but was called {{totalCount}} time(s).\");");
        w.Line($"{indent1}}}");
        w.Line();

        w.Line($"{indent1}/// <summary>Marks this event for verification by Stub.Verify(). Returns this for fluent chaining.</summary>");
        w.Line($"{indent1}public {evt.InterceptorClassName}{evt.TypeParameterList} Verifiable()");
        w.Line($"{indent1}{{");
        w.Line($"{indent1}\t_isVerifiable = true;");
        w.Line($"{indent1}\t_verifiableTimes = global::KnockOff.Times.AtLeastOnce;");
        w.Line($"{indent1}\treturn this;");
        w.Line($"{indent1}}}");
        w.Line();

        w.Line($"{indent1}/// <summary>Marks this event for verification by Stub.Verify() with Times constraint. Returns this for fluent chaining.</summary>");
        w.Line($"{indent1}public {evt.InterceptorClassName}{evt.TypeParameterList} Verifiable(global::KnockOff.Times times)");
        w.Line($"{indent1}{{");
        w.Line($"{indent1}\t_isVerifiable = true;");
        w.Line($"{indent1}\t_verifiableTimes = times;");
        w.Line($"{indent1}\treturn this;");
        w.Line($"{indent1}}}");
        w.Line();

        // Internal verification methods
        w.Line($"{indent1}internal bool IsVerifiable => _isVerifiable;");
        w.Line($"{indent1}internal bool IsConfigured => Handler != null;");
        w.Line();

        w.Line($"{indent1}/// <summary>Checks verification for Stub.Verify() - only verifiable items.</summary>");
        w.Line($"{indent1}internal global::KnockOff.VerificationFailure? CheckVerification()");
        w.Line($"{indent1}{{");
        w.Line($"{indent1}\tif (!_isVerifiable) return null;");
        w.Line($"{indent1}\tvar times = _verifiableTimes ?? global::KnockOff.Times.AtLeastOnce;");
        w.Line($"{indent1}\tvar totalCount = _addCount + _removeCount;");
        w.Line($"{indent1}\treturn times.Validate(totalCount) ? null : new global::KnockOff.VerificationFailure(\"{evt.EventName}\", times, totalCount);");
        w.Line($"{indent1}}}");
        w.Line();

        w.Line($"{indent1}/// <summary>Checks verification for Stub.VerifyAll() - all configured items.</summary>");
        w.Line($"{indent1}internal global::KnockOff.VerificationFailure? CheckVerificationAll()");
        w.Line($"{indent1}{{");
        w.Line($"{indent1}\tif (!IsConfigured && !_isVerifiable) return null;");
        w.Line($"{indent1}\tvar times = _verifiableTimes ?? global::KnockOff.Times.AtLeastOnce;");
        w.Line($"{indent1}\tvar totalCount = _addCount + _removeCount;");
        w.Line($"{indent1}\treturn times.Validate(totalCount) ? null : new global::KnockOff.VerificationFailure(\"{evt.EventName}\", times, totalCount);");
        w.Line($"{indent1}}}");

        w.Line($"{indent}}}");
        w.Line();
    }

    #endregion

    #region Wrapper Constructor Rendering

    private static void RenderWrapperConstructor(CodeWriter w, InlineConstructorModel ctor, string stubClassName, string typeParamList, string indent)
    {
        w.Line($"{indent}public {stubClassName}({ctor.ParameterDeclarations})");
        w.Line($"{indent}{{");
        if (string.IsNullOrEmpty(ctor.BaseCallArguments))
        {
            w.Line($"{indent}\tObject = new Impl(this);");
        }
        else
        {
            w.Line($"{indent}\tObject = new Impl(this, {ctor.BaseCallArguments});");
        }
        w.Line($"{indent}}}");
        w.Line();
    }

    private static void RenderVerifyMethods(CodeWriter w, StandaloneClassGenerationUnit unit, string indent, string indent1)
    {
        var interceptorPropertyNames = unit.InterceptorProperties
            .Select(p => p.PropertyName)
            .Distinct()
            .ToList();

        // Verify method
        w.Line($"{indent}/// <summary>Verifies all members marked with .Verifiable() were invoked as expected. Throws VerificationException with all failures if any fail.</summary>");
        w.Line($"{indent}public void Verify()");
        w.Line($"{indent}{{");
        w.Line($"{indent1}var failures = new global::System.Collections.Generic.List<global::KnockOff.VerificationFailure>();");
        w.Line();

        foreach (var name in interceptorPropertyNames)
        {
            w.Line($"{indent1}if ({name}.CheckVerification() is {{ }} {name.ToLowerInvariant()}Failure) failures.Add({name.ToLowerInvariant()}Failure);");
        }

        w.Line();
        w.Line($"{indent1}if (failures.Count > 0)");
        w.Line($"{indent1}\tthrow new global::KnockOff.VerificationException(failures);");
        w.Line($"{indent}}}");
        w.Line();

        // VerifyAll method
        w.Line($"{indent}/// <summary>Verifies ALL configured members were invoked at least once. Throws VerificationException with all failures if any fail.</summary>");
        w.Line($"{indent}public void VerifyAll()");
        w.Line($"{indent}{{");
        w.Line($"{indent1}var failures = new global::System.Collections.Generic.List<global::KnockOff.VerificationFailure>();");
        w.Line();

        foreach (var name in interceptorPropertyNames)
        {
            w.Line($"{indent1}if ({name}.CheckVerificationAll() is {{ }} {name.ToLowerInvariant()}Failure) failures.Add({name.ToLowerInvariant()}Failure);");
        }

        w.Line();
        w.Line($"{indent1}if (failures.Count > 0)");
        w.Line($"{indent1}\tthrow new global::KnockOff.VerificationException(failures);");
        w.Line($"{indent}}}");
        w.Line();
    }

    #endregion

    #region User Method Forwarders

    /// <summary>
    /// Generates internal forwarding methods for user method overrides.
    /// Standalone class interceptors are top-level classes (not nested inside the stub),
    /// so they cannot access protected virtual methods on the stub's base class.
    /// These internal forwarders bridge the gap: the interceptor calls stub.__UserMethod_X()
    /// which has internal access, and the forwarder delegates to the protected Execute_() method.
    /// </summary>
    private static void RenderUserMethodForwarders(CodeWriter w, StandaloneClassGenerationUnit unit, string indent)
    {
        var methodsWithUserOverride = unit.ImplMethods.Where(m => m.HasUserOverride).ToList();
        if (methodsWithUserOverride.Count == 0)
            return;

        foreach (var method in methodsWithUserOverride)
        {
            var forwarderName = $"__UserMethod_{method.MethodName}";
            var targetName = $"{method.MethodName}_";

            if (method.IsVoid)
            {
                if (string.IsNullOrEmpty(method.ParameterDeclarations))
                    w.Line($"{indent}internal void {forwarderName}() => {targetName}();");
                else
                    w.Line($"{indent}internal void {forwarderName}({method.ParameterDeclarations}) => {targetName}({method.ArgumentList});");
            }
            else
            {
                if (string.IsNullOrEmpty(method.ParameterDeclarations))
                    w.Line($"{indent}internal {method.ReturnType} {forwarderName}() => {targetName}();");
                else
                    w.Line($"{indent}internal {method.ReturnType} {forwarderName}({method.ParameterDeclarations}) => {targetName}({method.ArgumentList});");
            }
        }
        w.Line();
    }

    #endregion

    #region Impl Class Rendering

    private static void RenderImplClass(CodeWriter w, StandaloneClassGenerationUnit unit, string indent, string indent1, string indent2, string indent3)
    {
        var typeParamList = FormatTypeParameters(unit.TypeParameters);
        var stubClassName = unit.ClassName + typeParamList;

        // Suppress CS8618 for classes with required members
        if (unit.HasRequiredMembers)
        {
            w.Line("#pragma warning disable CS8618 // Non-nullable field must contain a non-null value when exiting constructor");
        }

        w.Line($"{indent}/// <summary>Internal implementation that inherits from {ExtractSimpleTypeName(unit.TargetClassName)}.</summary>");
        w.Line($"{indent}private sealed class Impl : {unit.TargetClassForInheritance}");
        w.Line($"{indent}{{");

        // Reference to the wrapper
        w.Line($"{indent1}private readonly {stubClassName} _stub;");
        w.Line();

        // Constructors
        foreach (var ctor in unit.Constructors)
        {
            RenderImplConstructor(w, ctor, stubClassName, unit.HasRequiredMembers, unit.RequiredMemberNames, indent1);
        }

        // Property overrides
        foreach (var prop in unit.ImplProperties)
        {
            RenderImplPropertyOverride(w, prop, indent1, indent2);
        }

        // Indexer overrides
        foreach (var indexer in unit.ImplIndexers)
        {
            RenderImplIndexerOverride(w, indexer, indent1, indent2);
        }

        // Method overrides
        foreach (var method in unit.ImplMethods)
        {
            RenderImplMethodOverride(w, method, indent1, indent2);
        }

        // Event overrides
        foreach (var evt in unit.ImplEvents)
        {
            RenderImplEventOverride(w, evt, indent1, indent2);
        }

        w.Line($"{indent}}}");

        if (unit.HasRequiredMembers)
        {
            w.Line("#pragma warning restore CS8618");
        }
    }

    private static void RenderImplConstructor(CodeWriter w, InlineConstructorModel ctor, string stubClassName, bool hasRequiredMembers, EquatableArray<string> requiredMemberNames, string indent)
    {
        var indent1 = indent + "\t";

        var paramList = string.IsNullOrEmpty(ctor.ParameterDeclarations)
            ? $"{stubClassName} stub"
            : $"{stubClassName} stub, {ctor.ParameterDeclarations}";

        if (hasRequiredMembers)
        {
            w.Line($"{indent}[global::System.Diagnostics.CodeAnalysis.SetsRequiredMembers]");
        }
        w.Line($"{indent}public Impl({paramList}) : base({ctor.BaseCallArguments})");
        w.Line($"{indent}{{");

        foreach (var memberName in requiredMemberNames)
        {
            w.Line($"{indent1}{memberName} = default!;");
        }

        w.Line($"{indent1}_stub = stub;");
        w.Line($"{indent}}}");
        w.Line();
    }

    private static void RenderImplPropertyOverride(CodeWriter w, InlineClassImplPropertyModel prop, string indent, string indent1)
    {
        var indent2 = indent1 + "\t";
        var requiredKeyword = prop.IsRequired ? "required " : "";

        w.Line($"{indent}/// <inheritdoc />");
        w.Line($"{indent}{requiredKeyword}{prop.AccessModifier} override {prop.ReturnType} {prop.PropertyName}");
        w.Line($"{indent}{{");

        if (prop.HasGetter)
        {
            w.Line($"{indent1}get");
            w.Line($"{indent1}{{");

            if (prop.HasUserOverride)
            {
                // User override pattern:
                // 1. Null check for calls during base constructor (fall back to base for virtual)
                // 2. OnGet supersedes user override (InvokeGetCallback tracks internally)
                // 3. Record access only for user override path (to avoid double counting)
                // 4. User override (virtual property with _ suffix in stub's base class)
                var fallback = prop.IsAbstract ? "default!" : $"base.{prop.PropertyName}";
                w.Line($"{indent2}if (_stub == null) return {fallback};");
                w.Line($"{indent2}if (_stub.{prop.PropertyName}.HasOnGet) return _stub.{prop.PropertyName}.InvokeGetCallback();");
                w.Line($"{indent2}_stub.{prop.PropertyName}.RecordGet();");
                w.Line($"{indent2}return _stub.{prop.PropertyName}_;");
            }
            else
            {
                // No user override - delegate to interceptor which handles full priority chain
                // (sequence > OnGet > strict/default) and falls back to base for virtual properties
                if (prop.IsAbstract)
                {
                    w.Line($"{indent2}if (_stub == null) return default!;");
                    w.Line($"{indent2}return _stub.{prop.PropertyName}.InvokeGet(_stub.Strict);");
                }
                else
                {
                    // For virtual properties, check if configured. If not, delegate to base.
                    w.Line($"{indent2}if (_stub == null) return base.{prop.PropertyName};");
                    w.Line($"{indent2}if (_stub.{prop.PropertyName}.IsConfigured) return _stub.{prop.PropertyName}.InvokeGet(_stub.Strict);");
                    w.Line($"{indent2}_stub.{prop.PropertyName}.InvokeGet(_stub.Strict);");
                    w.Line($"{indent2}return base.{prop.PropertyName};");
                }
            }
            w.Line($"{indent1}}}");
        }

        if (prop.HasSetter)
        {
            var setterKeyword = prop.IsInitOnly ? "init" : "set";
            w.Line($"{indent1}{setterKeyword}");
            w.Line($"{indent1}{{");

            if (prop.HasUserOverride)
            {
                // User override pattern:
                // 1. Null check for calls during base constructor (fall back to base for virtual)
                // 2. OnSet supersedes user override (InvokeSetCallback tracks internally)
                // 3. Record access only for user override path (to avoid double counting)
                // 4. User override (virtual property with _ suffix in stub's base class)
                if (prop.IsAbstract)
                {
                    w.Line($"{indent2}if (_stub == null) return;");
                }
                else
                {
                    w.Line($"{indent2}if (_stub == null) {{ base.{prop.PropertyName} = value; return; }}");
                }
                w.Line($"{indent2}if (_stub.{prop.PropertyName}.HasOnSet) {{ _stub.{prop.PropertyName}.InvokeSetCallback(value); return; }}");
                w.Line($"{indent2}_stub.{prop.PropertyName}.RecordSet(value);");
                w.Line($"{indent2}_stub.{prop.PropertyName}_ = value;");
            }
            else
            {
                // No user override - delegate to interceptor which handles full priority chain
                // (sequence > OnSet > strict/default) and falls back to base for virtual properties
                if (prop.IsAbstract)
                {
                    w.Line($"{indent2}if (_stub == null) return;");
                    w.Line($"{indent2}_stub.{prop.PropertyName}.InvokeSet(_stub.Strict, value);");
                }
                else
                {
                    // For virtual properties, check if configured. If not, delegate to base.
                    w.Line($"{indent2}if (_stub == null) {{ base.{prop.PropertyName} = value; return; }}");
                    w.Line($"{indent2}_stub.{prop.PropertyName}.InvokeSet(_stub.Strict, value);");
                    w.Line($"{indent2}if (!_stub.{prop.PropertyName}.IsConfigured) base.{prop.PropertyName} = value;");
                }
            }
            w.Line($"{indent1}}}");
        }

        w.Line($"{indent}}}");
        w.Line();
    }

    private static void RenderImplIndexerOverride(CodeWriter w, InlineClassImplIndexerModel indexer, string indent, string indent1)
    {
        var indent2 = indent1 + "\t";

        w.Line($"{indent}/// <inheritdoc />");
        w.Line($"{indent}{indexer.AccessModifier} override {indexer.ReturnType} this[{indexer.ParameterDeclarations}]");
        w.Line($"{indent}{{");

        if (indexer.HasGetter)
        {
            w.Line($"{indent1}get");
            w.Line($"{indent1}{{");
            if (indexer.IsAbstract)
            {
                var defaultExpr = indexer.IsNullable ? "default" : GetDefaultForType(indexer.ReturnType, indexer.DefaultStrategy, indexer.ConcreteTypeForNew);
                w.Line($"{indent2}if (_stub == null) return {defaultExpr};");
                w.Line($"{indent2}return _stub.{indexer.IndexerName}.InvokeGet(_stub.Strict, {indexer.ArgumentList});");
            }
            else
            {
                w.Line($"{indent2}if (_stub == null) return base[{indexer.ArgumentList}];");
                w.Line($"{indent2}if (_stub.{indexer.IndexerName}.IsConfigured) return _stub.{indexer.IndexerName}.InvokeGet(_stub.Strict, {indexer.ArgumentList});");
                w.Line($"{indent2}_stub.{indexer.IndexerName}.InvokeGet(_stub.Strict, {indexer.ArgumentList});");
                w.Line($"{indent2}return base[{indexer.ArgumentList}];");
            }
            w.Line($"{indent1}}}");
        }

        if (indexer.HasSetter)
        {
            w.Line($"{indent1}set");
            w.Line($"{indent1}{{");
            if (indexer.IsAbstract)
            {
                w.Line($"{indent2}if (_stub == null) return;");
                w.Line($"{indent2}_stub.{indexer.IndexerName}.InvokeSet(_stub.Strict, {indexer.ArgumentList}, value);");
            }
            else
            {
                w.Line($"{indent2}if (_stub == null) {{ base[{indexer.ArgumentList}] = value; return; }}");
                w.Line($"{indent2}_stub.{indexer.IndexerName}.InvokeSet(_stub.Strict, {indexer.ArgumentList}, value);");
                w.Line($"{indent2}if (!_stub.{indexer.IndexerName}.IsConfigured) base[{indexer.ArgumentList}] = value;");
            }
            w.Line($"{indent1}}}");
        }

        w.Line($"{indent}}}");
        w.Line();
    }

    private static void RenderImplMethodOverride(CodeWriter w, InlineClassImplMethodModel method, string indent, string indent1)
    {
        w.Line($"{indent}/// <inheritdoc />");
        w.Line($"{indent}{method.AccessModifier} override {method.ReturnType} {method.MethodName}({method.ParameterDeclarations})");
        w.Line($"{indent}{{");

        var invokeMethodName = string.IsNullOrEmpty(method.InvokeSuffix)
            ? "Invoke"
            : $"Invoke{method.InvokeSuffix}";

        if (method.HasUserOverride)
        {
            // User method override pattern:
            // The interceptor handles user method fallback internally via stub.MethodName_()
            // Pass _stub to Invoke() so the interceptor can call the user method when unconfigured
            // No base.Method() call -- user method completely replaces base call (Design Decision 1)

            // Null check for calls during base constructor
            if (method.IsVoid)
            {
                w.Line($"{indent1}if (_stub == null) return;");
                var invokeArgs = "_stub.Strict, _stub" + (string.IsNullOrEmpty(method.InputArgumentList) ? "" : $", {method.InputArgumentList}");
                w.Line($"{indent1}_stub.{method.HandlerName}.{invokeMethodName}({invokeArgs});");
            }
            else
            {
                w.Line($"{indent1}if (_stub == null) return default!;");
                var invokeArgs = "_stub.Strict, _stub" + (string.IsNullOrEmpty(method.InputArgumentList) ? "" : $", {method.InputArgumentList}");
                w.Line($"{indent1}return _stub.{method.HandlerName}.{invokeMethodName}({invokeArgs});");
            }
        }
        else
        {
            // Standard interceptor pattern (no user method override)

            // Null check for calls during base constructor
            w.Line($"{indent1}if (_stub == null)");
            w.Line($"{indent1}{{");
            if (method.IsAbstract)
            {
                if (method.IsVoid)
                    w.Line($"{indent1}\treturn;");
                else if (method.IsTask)
                    w.Line($"{indent1}\treturn global::System.Threading.Tasks.Task.CompletedTask;");
                else if (method.IsValueTask)
                    w.Line($"{indent1}\treturn default;");
                else
                    w.Line($"{indent1}\treturn default!;");
            }
            else
            {
                if (method.IsVoid)
                {
                    w.Line($"{indent1}\tbase.{method.MethodName}({method.ArgumentList});");
                    w.Line($"{indent1}\treturn;");
                }
                else
                {
                    w.Line($"{indent1}\treturn base.{method.MethodName}({method.ArgumentList});");
                }
            }
            w.Line($"{indent1}}}");
            w.Line();

            var invokeArgs = "_stub.Strict" + (string.IsNullOrEmpty(method.InputArgumentList) ? "" : $", {method.InputArgumentList}");

            if (method.IsAbstract)
            {
                if (method.IsVoid)
                    w.Line($"{indent1}_stub.{method.HandlerName}.{invokeMethodName}({invokeArgs});");
                else
                    w.Line($"{indent1}return _stub.{method.HandlerName}.{invokeMethodName}({invokeArgs});");
            }
            else
            {
                w.Line($"{indent1}var unconfiguredBefore = _stub.{method.HandlerName}.UnconfiguredCallCount;");
                if (method.IsVoid)
                {
                    w.Line($"{indent1}_stub.{method.HandlerName}.{invokeMethodName}({invokeArgs});");
                    w.Line($"{indent1}if (_stub.{method.HandlerName}.UnconfiguredCallCount > unconfiguredBefore)");
                    w.Line($"{indent1}{{");
                    w.Line($"{indent1}\tbase.{method.MethodName}({method.ArgumentList});");
                    w.Line($"{indent1}}}");
                }
                else
                {
                    w.Line($"{indent1}var result = _stub.{method.HandlerName}.{invokeMethodName}({invokeArgs});");
                    w.Line($"{indent1}if (_stub.{method.HandlerName}.UnconfiguredCallCount > unconfiguredBefore)");
                    w.Line($"{indent1}{{");
                    w.Line($"{indent1}\treturn base.{method.MethodName}({method.ArgumentList});");
                    w.Line($"{indent1}}}");
                    w.Line($"{indent1}return result;");
                }
            }
        }

        w.Line($"{indent}}}");
        w.Line();
    }

    private static void RenderImplEventOverride(CodeWriter w, InlineClassImplEventModel evt, string indent, string indent1)
    {
        w.Line($"{indent}/// <inheritdoc />");
        w.Line($"{indent}public override event {evt.DelegateType}? {evt.EventName}");
        w.Line($"{indent}{{");
        w.Line($"{indent1}add => _stub?.{evt.EventName}.RecordAdd(value);");
        w.Line($"{indent1}remove => _stub?.{evt.EventName}.RecordRemove(value);");
        w.Line($"{indent}}}");
        w.Line();
    }

