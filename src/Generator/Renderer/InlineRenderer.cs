    private static void RenderDelegateStub(CodeWriter w, InlineDelegateStubModel del)
    {
        // Convert delegate model to unified method interceptor model
        var (model, options) = ModelAdapters.ToUnifiedModel(del);

        // Render interceptor class using shared renderer
        var previousIndent = w.Indent;
        w.SetIndent(2);
        MethodInterceptorRenderer.RenderInterceptorClass(w, model, options);
        w.SetIndent(previousIndent);

        // Render thin stub class shell
        w.Line($"\t\t/// <summary>Stub for {del.DelegateType} delegate.</summary>");
        w.Line($"\t\tpublic sealed class {del.StubClassName}{del.TypeParameterList} : global::KnockOff.IKnockOffStub{del.ConstraintClauses}");
        w.Line("\t\t{");

        // Strict property
        w.Line("\t\t\t/// <summary>When true, unconfigured delegate calls throw StubException instead of returning default.</summary>");
        w.Line("\t\t\tpublic bool Strict { get; set; }");
        w.Line();

        // Interceptor property (generic if delegate is open generic)
        w.Line($"\t\t\t/// <summary>Interceptor for tracking and configuring delegate behavior.</summary>");
        w.Line($"\t\t\tpublic {del.InterceptorClassName}{del.TypeParameterList} Interceptor {{ get; }} = new();");
        w.Line();

        // Private Invoke method - delegates to Interceptor.Invoke(Strict, args)
        // NOTE: Do NOT call Interceptor.RecordCall() here - Interceptor.Invoke() handles all tracking internally
        w.Line($"\t\t\tprivate {del.ReturnType} Invoke({del.InvokeParameterDeclarations})");
        w.Line("\t\t\t{");
        var invokeArgs = del.Parameters.Count > 0
            ? $"Strict, {del.InvokeArgumentList}"
            : "Strict";
        if (del.IsVoid)
        {
            w.Line($"\t\t\t\tInterceptor.Invoke({invokeArgs});");
        }
        else
        {
            w.Line($"\t\t\t\treturn Interceptor.Invoke({invokeArgs});");
        }
        w.Line("\t\t\t}");
        w.Line();

        // Implicit conversion operator
        w.Line($"\t\t\t/// <summary>Implicit conversion to {del.DelegateType}.</summary>");
        w.Line($"\t\t\tpublic static implicit operator {del.DelegateType}({del.StubClassName}{del.TypeParameterList} stub) => stub.Invoke;");

        w.Line("\t\t}");
        w.Line();
    }


