#nullable enable
using System.Collections.Generic;
using System.Linq;
using KnockOff.Model.Inline;
using KnockOff.Model.Shared;
using KnockOff.Renderer.Shared;

namespace KnockOff.Renderer;

/// <summary>
/// Renders InlineGenerationUnit to source code string.
/// Pure emission - no decisions, just output what the model says.
/// </summary>
internal static class InlineRenderer
{
    public static string Render(InlineGenerationUnit unit)
    {
        var w = new CodeWriter();

        w.Line("// <auto-generated/>");
        w.Line("#nullable enable");
        w.Line();

        // Always include System.Linq - needed for .Sum() in overload TotalCallCount and generic methods
        w.Line("using System.Linq;");
        w.Line();

        // Namespace
        if (!string.IsNullOrEmpty(unit.Namespace))
        {
            w.Line($"namespace {unit.Namespace};");
            w.Line();
        }

        // Open containing type wrappers for nested classes
        foreach (var containingType in unit.ContainingTypes)
        {
            var accessMod = string.IsNullOrEmpty(containingType.AccessModifier)
                ? ""
                : containingType.AccessModifier + " ";
            w.Line($"{accessMod}partial {containingType.Keyword} {containingType.Name}");
            w.Line("{");
        }

        // Partial class
        w.Line($"partial class {unit.ClassName}");
        w.Line("{");

        // Nested Stubs class
        w.Line("\t/// <summary>Contains stub implementations for inline stub pattern.</summary>");
        w.Line("\tpublic static class Stubs");
        w.Line("\t{");

        // Check if any interface has generic methods - if so, generate helper interfaces
        if (unit.HasGenericMethods)
        {
            w.Line("\t\tprivate interface IGenericMethodCallTracker { int CallCount { get; } }");
            w.Line("\t\tprivate interface IResettable { void Reset(); }");
            w.Line();
        }

        // Render interface stubs
        foreach (var ifaceStub in unit.InterfaceStubs)
        {
            RenderInterfaceStub(w, ifaceStub);
        }

        // Render delegate stubs
        foreach (var delStub in unit.DelegateStubs)
        {
            RenderDelegateStub(w, delStub);
        }

        // Render class stubs
        foreach (var classStub in unit.ClassStubs)
        {
            RenderClassStub(w, classStub);
        }

        w.Line("\t}"); // Close Stubs class

        // Render partial property implementations
        foreach (var prop in unit.PartialProperties)
        {
            RenderPartialProperty(w, prop);
        }

        w.Line("}"); // Close partial class

        // Close containing type wrappers
        for (int i = 0; i < unit.ContainingTypes.Count; i++)
        {
            w.Line("}");
        }

        return w.ToString();
    }

    #region Interface Stub Rendering

    private static void RenderInterfaceStub(CodeWriter w, InlineInterfaceStubModel iface)
    {
        // Use shared renderers for property and indexer interceptors
        var typeParams = FormatTypeParameterList(iface.TypeParameters);
        var constraints = FormatConstraints(iface.TypeParameters);
        var previousIndent = w.Indent;
        w.SetIndent(2);  // Inline stubs are nested 2 levels deep

        // Render property interceptor classes using shared renderer
        foreach (var prop in iface.Properties)
        {
            var unifiedModel = ModelAdapters.ToUnifiedPropertyModel(prop);
            // Use property-specific type parameters (may differ from interface-level for open generics)
            var options = new PropertyInterceptorRenderOptions(
                BaseIndent: 2,
                IncludeStrictParameter: true,
                StrictAccessExpression: "strict",
                InterceptorTypeParameters: prop.TypeParameterList,
                InterceptorConstraints: prop.ConstraintClauses);
            PropertyInterceptorRenderer.RenderInterceptorClass(w, unifiedModel, options);
        }

        // Render indexer interceptor classes using shared renderer
        foreach (var indexer in iface.Indexers)
        {
            var unifiedModel = ModelAdapters.ToUnifiedIndexerModel(indexer);
            // Use indexer-specific type parameters (may differ from interface-level for open generics)
            var options = new IndexerInterceptorRenderOptions(
                BaseIndent: 2,
                IncludeStrictParameter: true,
                StrictAccessExpression: "strict",
                InterceptorTypeParameters: indexer.TypeParameterList,
                InterceptorConstraints: indexer.ConstraintClauses);
            IndexerInterceptorRenderer.RenderInterceptorClass(w, unifiedModel, options);
        }

        w.SetIndent(previousIndent);

        // Render container classes for multi-indexer groups
        foreach (var group in iface.IndexerGroups)
        {
            if (group.Indexers.Count > 1)
            {
                RenderIndexerContainerClass(w, group);
            }
        }

        // Use shared renderer for method interceptors
        // Set indent level for nested class context (inside partial class and Stubs class)
        var methodTypeParams = FormatTypeParameterList(iface.TypeParameters);
        var methodConstraints = FormatConstraints(iface.TypeParameters);
        previousIndent = w.Indent;
        w.SetIndent(2);  // Inline stubs are nested 2 levels deep
        foreach (var method in iface.Methods)
        {
            var options = new InterceptorRenderOptions(
                BaseIndent: 2,
                IncludeStrictParameter: true,
                StrictAccessExpression: "strict",
                InterceptorTypeParameters: methodTypeParams,
                InterceptorConstraints: methodConstraints);
            MethodInterceptorRenderer.RenderInterceptorClass(w, method, options);
        }
        w.SetIndent(previousIndent);

        foreach (var handler in iface.GenericMethodHandlers)
        {
            RenderGenericMethodHandler(w, handler);
        }

        foreach (var evt in iface.Events)
        {
            RenderEventInterceptorClass(w, evt, iface.StubClassName);
        }

        // Render the stub class
        var stubTypeParamList = FormatTypeParameterList(iface.TypeParameters);
        var stubConstraints = FormatConstraints(iface.TypeParameters);

        w.Line($"\t\t/// <summary>Stub implementation of {iface.BaseType}.</summary>");
        w.Line($"\t\tpublic class {iface.StubClassName}{stubTypeParamList} : {iface.BaseType}, global::KnockOff.IKnockOffStub{stubConstraints}");
        w.Line("\t\t{");

        // Interceptor properties
        foreach (var interceptorProp in iface.InterceptorProperties)
        {
            var newKeyword = interceptorProp.NeedsNewKeyword ? "new " : "";
            w.Line($"\t\t\t/// <summary>{interceptorProp.Description}</summary>");
            w.Line($"\t\t\tpublic {newKeyword}{interceptorProp.InterceptorTypeName} {interceptorProp.PropertyName} {{ get; }} = new();");
            w.Line();
        }

        // Explicit interface implementations
        foreach (var impl in iface.Implementations)
        {
            RenderImplementation(w, impl);
        }

        // Object property
        w.Line($"\t\t\t/// <summary>The {iface.BaseType} instance. Use for passing to code expecting the interface.</summary>");
        w.Line($"\t\t\tpublic {iface.BaseType} Object => this;");
        w.Line();

        // Strict property and constructor
        var strictDefault = iface.Strict ? "true" : "false";
        w.Line("\t\t\t/// <summary>When true, unconfigured method calls throw StubException instead of returning default.</summary>");
        w.Line($"\t\t\tpublic bool Strict {{ get; set; }} = {strictDefault};");
        w.Line();
        w.Line($"\t\t\t/// <summary>Creates a new instance of the stub.</summary>");
        w.Line($"\t\t\t/// <param name=\"strict\">When true, unconfigured method calls throw StubException.</param>");
        w.Line($"\t\t\tpublic {iface.StubClassName}(bool strict = {strictDefault})");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tStrict = strict;");
        w.Line("\t\t\t}");
        w.Line();

        // Source(T) methods for Source feature
        RenderSourceMethods(w, iface);

        // SmartDefault helper if interface has generic methods
        if (iface.HasGenericMethods)
        {
            RenderSmartDefaultMethod(w);
        }

        // Verify and VerifyAll methods
        RenderInlineVerifyMethods(w, iface);

        w.Line("\t\t}");
        w.Line();
    }

    private static void RenderInlineVerifyMethods(CodeWriter w, InlineInterfaceStubModel iface)
    {
        // Get unique interceptor property names (the actual property names on the stub class)
        var interceptorPropertyNames = iface.InterceptorProperties
            .Select(p => p.PropertyName)
            .Distinct()
            .ToList();

        // Verify method - checks only .Verifiable() items, throws if any fail
        w.Line("\t\t\t/// <summary>Verifies all members marked with .Verifiable() were invoked as expected. Throws VerificationException with all failures if any fail.</summary>");
        w.Line("\t\t\tpublic void Verify()");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tvar failures = new global::System.Collections.Generic.List<global::KnockOff.VerificationFailure>();");
        w.Line();

        // Check all interceptors (methods and properties share the same pattern)
        foreach (var name in interceptorPropertyNames)
        {
            w.Line($"\t\t\t\tif ({name}.CheckVerification() is {{ }} {name.ToLowerInvariant()}Failure) failures.Add({name.ToLowerInvariant()}Failure);");
        }

        w.Line();
        w.Line("\t\t\t\tif (failures.Count > 0)");
        w.Line("\t\t\t\t\tthrow new global::KnockOff.VerificationException(failures);");
        w.Line("\t\t\t}");
        w.Line();

        // VerifyAll method - checks ALL configured members, throws if any fail
        w.Line("\t\t\t/// <summary>Verifies ALL configured members were invoked at least once. Throws VerificationException with all failures if any fail.</summary>");
        w.Line("\t\t\tpublic void VerifyAll()");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tvar failures = new global::System.Collections.Generic.List<global::KnockOff.VerificationFailure>();");
        w.Line();

        // Check all configured interceptors
        foreach (var name in interceptorPropertyNames)
        {
            w.Line($"\t\t\t\tif ({name}.CheckVerificationAll() is {{ }} {name.ToLowerInvariant()}Failure) failures.Add({name.ToLowerInvariant()}Failure);");
        }

        w.Line();
        w.Line("\t\t\t\tif (failures.Count > 0)");
        w.Line("\t\t\t\t\tthrow new global::KnockOff.VerificationException(failures);");
        w.Line("\t\t\t}");
        w.Line();
    }

    private static void RenderPropertyInterceptorClass(CodeWriter w, InlinePropertyModel prop, string stubClassName)
    {
        var typeParamList = prop.TypeParameterList;
        var constraintClause = prop.ConstraintClauses;

        w.Line($"\t\t/// <summary>Interceptor for {stubClassName}.{prop.PropertyName}.</summary>");
        w.Line($"\t\tpublic sealed class {prop.InterceptorClassName}{typeParamList}{constraintClause}");
        w.Line("\t\t{");

        // Verifiable state
        w.Line("\t\t\tprivate bool _isVerifiable;");
        w.Line("\t\t\tprivate global::KnockOff.Called? _verifiableTimes;");
        w.Line("\t\t\tprivate bool _valueSet;");
        w.Line();

        if (prop.HasGetter)
        {
            w.Line("\t\t\tprivate int _getCount;");
            w.Line();
            w.Line($"\t\t\t/// <summary>Callback for getter. If set, returns its value.</summary>");
            w.Line($"\t\t\tpublic global::System.Func<{prop.ReturnType}>? Get {{ get; set; }}");
            w.Line();
        }

        if (prop.HasSetter)
        {
            w.Line("\t\t\tprivate int _setCount;");
            w.Line();
            w.Line($"\t\t\t/// <summary>The last value passed to the setter.</summary>");
            w.Line($"\t\t\tpublic {prop.NullableReturnType} LastSetValue {{ get; private set; }}");
            w.Line();
            w.Line($"\t\t\t/// <summary>Callback for setter.</summary>");
            w.Line($"\t\t\tpublic global::System.Action<{prop.ReturnType}>? Set {{ get; set; }}");
            w.Line();
        }

        // Value property with backing field - setting Value marks the property as configured
        w.Line($"\t\t\tprivate {prop.ReturnType} _value = default!;");
        w.Line($"\t\t\t/// <summary>Value returned by getter when Get is not set. Setting this marks the property as configured.</summary>");
        w.Line($"\t\t\tpublic {prop.ReturnType} Value");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tget => _value;");
        w.Line("\t\t\t\tset { _value = value; _valueSet = true; }");
        w.Line("\t\t\t}");
        w.Line();

        // Source field for Source(T) feature - skip for init-only properties
        if (!string.IsNullOrEmpty(prop.DeclaringInterface) && !prop.IsInitOnly)
        {
            w.Line($"\t\t\t/// <summary>Source object for delegation when Get is not set.</summary>");
            w.Line($"\t\t\tinternal {prop.DeclaringInterface}? _source;");
            w.Line();
        }

        // RecordGet/RecordSet
        if (prop.HasGetter)
        {
            w.Line("\t\t\t/// <summary>Records a getter access.</summary>");
            w.Line("\t\t\tpublic void RecordGet() => _getCount++;");
            w.Line();
        }
        if (prop.HasSetter)
        {
            w.Line("\t\t\t/// <summary>Records a setter access.</summary>");
            w.Line($"\t\t\tpublic void RecordSet({prop.NullableReturnType} value) {{ _setCount++; LastSetValue = value; }}");
            w.Line();
        }

        // Reset method - clears tracking state but preserves configuration (Get/Set/Value) and verifiable marking
        w.Line("\t\t\t/// <summary>Resets tracking state (counts, LastSetValue) but preserves configuration (Get, Set, Value) and verifiable marking.</summary>");
        var resetParts = new List<string>();
        if (prop.HasGetter) resetParts.Add("_getCount = 0;");
        if (prop.HasSetter) resetParts.Add("_setCount = 0; LastSetValue = default;");
        if (!string.IsNullOrEmpty(prop.DeclaringInterface) && !prop.IsInitOnly) resetParts.Add("_source = null;");
        w.Line($"\t\t\tpublic void Reset() {{ {string.Join(" ", resetParts)} }}");
        w.Line();

        // Verifiable methods (fluent)
        w.Line($"\t\t\t/// <summary>Marks this property for verification by Stub.Verify(). Returns this for fluent chaining.</summary>");
        w.Line($"\t\t\tpublic {prop.InterceptorClassName}{typeParamList} Verifiable() {{ _isVerifiable = true; _verifiableTimes = null; return this; }}");
        w.Line();
        w.Line($"\t\t\t/// <summary>Marks this property for verification by Stub.Verify() with Called constraint. Returns this for fluent chaining.</summary>");
        w.Line($"\t\t\tpublic {prop.InterceptorClassName}{typeParamList} Verifiable(global::KnockOff.Called times) {{ _isVerifiable = true; _verifiableTimes = times; return this; }}");
        w.Line();

        // Verify methods - throw on failure
        // Build total count expression based on available accessors
        var totalCountExpr = prop.HasGetter && prop.HasSetter
            ? "_getCount + _setCount"
            : (prop.HasGetter ? "_getCount" : "_setCount");

        w.Line("\t\t\t/// <summary>Verifies the property was accessed at least once. Throws VerificationException if not.</summary>");
        w.Line("\t\t\tpublic void Verify() => Verify(global::KnockOff.Called.AtLeastOnce);");
        w.Line();

        w.Line("\t\t\t/// <summary>Verifies total access count satisfies the Called constraint. Throws VerificationException if not.</summary>");
        w.Line("\t\t\tpublic void Verify(global::KnockOff.Called times)");
        w.Line("\t\t\t{");
        w.Line($"\t\t\t\tvar totalCount = {totalCountExpr};");
        w.Line("\t\t\t\tif (!times.Validate(totalCount))");
        w.Line($"\t\t\t\t\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"{prop.PropertyName}\", times, totalCount));");
        w.Line("\t\t\t}");
        w.Line();

        // VerifyGet methods
        if (prop.HasGetter)
        {
            w.Line("\t\t\t/// <summary>Verifies the getter was accessed at least once. Throws VerificationException if not.</summary>");
            w.Line("\t\t\tpublic void VerifyGet() => VerifyGet(global::KnockOff.Called.AtLeastOnce);");
            w.Line();

            w.Line("\t\t\t/// <summary>Verifies getter access count satisfies the Called constraint. Throws VerificationException if not.</summary>");
            w.Line("\t\t\tpublic void VerifyGet(global::KnockOff.Called times)");
            w.Line("\t\t\t{");
            w.Line("\t\t\t\tif (!times.Validate(_getCount))");
            w.Line($"\t\t\t\t\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"{prop.PropertyName} (get)\", times, _getCount));");
            w.Line("\t\t\t}");
            w.Line();
        }

        // VerifySet methods
        if (prop.HasSetter)
        {
            w.Line("\t\t\t/// <summary>Verifies the setter was accessed at least once. Throws VerificationException if not.</summary>");
            w.Line("\t\t\tpublic void VerifySet() => VerifySet(global::KnockOff.Called.AtLeastOnce);");
            w.Line();

            w.Line("\t\t\t/// <summary>Verifies setter access count satisfies the Called constraint. Throws VerificationException if not.</summary>");
            w.Line("\t\t\tpublic void VerifySet(global::KnockOff.Called times)");
            w.Line("\t\t\t{");
            w.Line("\t\t\t\tif (!times.Validate(_setCount))");
            w.Line($"\t\t\t\t\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"{prop.PropertyName} (set)\", times, _setCount));");
            w.Line("\t\t\t}");
            w.Line();
        }

        // Internal verification support for stub-level Verify/VerifyAll
        w.Line("\t\t\t/// <summary>Whether this property was marked with Verifiable().</summary>");
        w.Line("\t\t\tinternal bool IsVerifiable => _isVerifiable;");
        w.Line();

        // IsConfigured - Value set OR Get/Set callback registered
        var isConfiguredParts = new List<string> { "_valueSet" };
        if (prop.HasGetter) isConfiguredParts.Add("Get != null");
        if (prop.HasSetter) isConfiguredParts.Add("Set != null");
        w.Line("\t\t\t/// <summary>Whether this property has been configured (Value set or callbacks registered).</summary>");
        w.Line($"\t\t\tinternal bool IsConfigured => {string.Join(" || ", isConfiguredParts)};");
        w.Line();

        w.Line("\t\t\t/// <summary>Checks verification for Stub.Verify() - only checks if marked verifiable.</summary>");
        w.Line("\t\t\tinternal global::KnockOff.VerificationFailure? CheckVerification()");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tif (!_isVerifiable) return null;");
        w.Line("\t\t\t\tvar times = _verifiableTimes ?? global::KnockOff.Called.AtLeastOnce;");
        w.Line($"\t\t\t\tvar totalCount = {totalCountExpr};");
        w.Line($"\t\t\t\treturn times.Validate(totalCount) ? null : new global::KnockOff.VerificationFailure(\"{prop.PropertyName}\", times, totalCount);");
        w.Line("\t\t\t}");
        w.Line();

        w.Line("\t\t\t/// <summary>Checks verification for Stub.VerifyAll() - checks if configured.</summary>");
        w.Line("\t\t\tinternal global::KnockOff.VerificationFailure? CheckVerificationAll()");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tif (!IsConfigured) return null;");
        w.Line($"\t\t\t\tvar totalCount = {totalCountExpr};");
        w.Line($"\t\t\t\treturn totalCount >= 1 ? null : new global::KnockOff.VerificationFailure(\"{prop.PropertyName}\", global::KnockOff.Called.AtLeastOnce, totalCount);");
        w.Line("\t\t\t}");

        w.Line("\t\t}");
        w.Line();
    }

    private static void RenderIndexerInterceptorClass(CodeWriter w, InlineIndexerModel indexer, string stubClassName)
    {
        var typeParamList = indexer.TypeParameterList;
        var constraintClause = indexer.ConstraintClauses;

        w.Line($"\t\t/// <summary>Interceptor for {stubClassName}.{indexer.IndexerName}.</summary>");
        w.Line($"\t\tpublic sealed class {indexer.InterceptorClassName}{typeParamList}{constraintClause}");
        w.Line("\t\t{");

        // Verifiable state
        w.Line("\t\t\tprivate bool _isVerifiable;");
        w.Line("\t\t\tprivate global::KnockOff.Called? _verifiableTimes;");
        w.Line("\t\t\tprivate bool _configured;");
        w.Line();

        if (indexer.HasGetter)
        {
            w.Line("\t\t\tprivate int _getCount;");
            w.Line();
            w.Line($"\t\t\t/// <summary>The last key used to access the getter.</summary>");
            w.Line($"\t\t\tpublic {indexer.NullableKeyType} LastGetKey {{ get; private set; }}");
            w.Line();
            w.Line($"\t\t\tprivate global::System.Func<{indexer.ParameterTypes}, {indexer.ReturnType}>? _get;");
            w.Line($"\t\t\t/// <summary>Callback for getter. Setting this marks the indexer as configured.</summary>");
            w.Line($"\t\t\tpublic global::System.Func<{indexer.ParameterTypes}, {indexer.ReturnType}>? Get");
            w.Line("\t\t\t{");
            w.Line("\t\t\t\tget => _get;");
            w.Line("\t\t\t\tset { _get = value; if (value != null) _configured = true; }");
            w.Line("\t\t\t}");
            w.Line();
        }

        if (indexer.HasSetter)
        {
            w.Line("\t\t\tprivate int _setCount;");
            w.Line();
            w.Line($"\t\t\t/// <summary>The last key-value pair passed to the setter.</summary>");
            w.Line($"\t\t\tpublic ({indexer.KeyType} Key, {indexer.ReturnType} Value)? LastSetEntry {{ get; private set; }}");
            w.Line();
            w.Line($"\t\t\tprivate global::System.Action<{indexer.ParameterTypes}, {indexer.ReturnType}>? _set;");
            w.Line($"\t\t\t/// <summary>Callback for setter. Setting this marks the indexer as configured.</summary>");
            w.Line($"\t\t\tpublic global::System.Action<{indexer.ParameterTypes}, {indexer.ReturnType}>? Set");
            w.Line("\t\t\t{");
            w.Line("\t\t\t\tget => _set;");
            w.Line("\t\t\t\tset { _set = value; if (value != null) _configured = true; }");
            w.Line("\t\t\t}");
            w.Line();
        }

        // RecordGet/RecordSet
        if (indexer.HasGetter)
        {
            w.Line($"\t\t\t/// <summary>Records a getter access.</summary>");
            w.Line($"\t\t\tpublic void RecordGet({indexer.ParameterSignature}) {{ _getCount++; LastGetKey = {indexer.KeyExpression}; }}");
            w.Line();
        }
        if (indexer.HasSetter)
        {
            w.Line($"\t\t\t/// <summary>Records a setter access.</summary>");
            w.Line($"\t\t\tpublic void RecordSet({indexer.ParameterSignature}, {indexer.ReturnType} value) {{ _setCount++; LastSetEntry = ({indexer.KeyExpression}, value); }}");
            w.Line();
        }

        // Backing dictionary
        w.Line($"\t\t\t/// <summary>Backing storage for this indexer.</summary>");
        w.Line($"\t\t\tpublic global::System.Collections.Generic.Dictionary<{indexer.SingleKeyType}, {indexer.ReturnType}> Backing {{ get; }} = new();");
        w.Line();

        // Source field for Source(T) feature
        if (!string.IsNullOrEmpty(indexer.DeclaringInterface))
        {
            w.Line($"\t\t\t/// <summary>Source object for delegation when Get/Set is not set.</summary>");
            w.Line($"\t\t\tinternal {indexer.DeclaringInterface}? _source;");
            w.Line();
        }

        // Reset method - clears tracking state but preserves configuration (Get/Set/Backing) and verifiable marking
        w.Line("\t\t\t/// <summary>Resets tracking state (counts, LastGetKey, LastSetEntry) but preserves configuration (Get, Set, Backing) and verifiable marking.</summary>");
        var resetParts = new List<string>();
        if (indexer.HasGetter) resetParts.Add("_getCount = 0; LastGetKey = default;");
        if (indexer.HasSetter) resetParts.Add("_setCount = 0; LastSetEntry = default;");
        if (!string.IsNullOrEmpty(indexer.DeclaringInterface)) resetParts.Add("_source = null;");
        w.Line($"\t\t\tpublic void Reset() {{ {string.Join(" ", resetParts)} }}");
        w.Line();

        // Build total count expression based on available accessors
        var totalCountExpr = indexer.HasGetter && indexer.HasSetter
            ? "_getCount + _setCount"
            : (indexer.HasGetter ? "_getCount" : "_setCount");

        // Verifiable methods (fluent)
        w.Line($"\t\t\t/// <summary>Marks this indexer for verification by Stub.Verify(). Returns this for fluent chaining.</summary>");
        w.Line($"\t\t\tpublic {indexer.InterceptorClassName}{typeParamList} Verifiable() {{ _isVerifiable = true; _verifiableTimes = null; return this; }}");
        w.Line();
        w.Line($"\t\t\t/// <summary>Marks this indexer for verification by Stub.Verify() with Called constraint. Returns this for fluent chaining.</summary>");
        w.Line($"\t\t\tpublic {indexer.InterceptorClassName}{typeParamList} Verifiable(global::KnockOff.Called times) {{ _isVerifiable = true; _verifiableTimes = times; return this; }}");
        w.Line();

        // Verify methods - throw on failure
        w.Line("\t\t\t/// <summary>Verifies the indexer was accessed at least once. Throws VerificationException if not.</summary>");
        w.Line("\t\t\tpublic void Verify() => Verify(global::KnockOff.Called.AtLeastOnce);");
        w.Line();

        w.Line("\t\t\t/// <summary>Verifies total access count satisfies the Called constraint. Throws VerificationException if not.</summary>");
        w.Line("\t\t\tpublic void Verify(global::KnockOff.Called times)");
        w.Line("\t\t\t{");
        w.Line($"\t\t\t\tvar totalCount = {totalCountExpr};");
        w.Line("\t\t\t\tif (!times.Validate(totalCount))");
        w.Line($"\t\t\t\t\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"{indexer.IndexerName}\", times, totalCount));");
        w.Line("\t\t\t}");
        w.Line();

        // VerifyGet methods
        if (indexer.HasGetter)
        {
            w.Line("\t\t\t/// <summary>Verifies the getter was accessed at least once. Throws VerificationException if not.</summary>");
            w.Line("\t\t\tpublic void VerifyGet() => VerifyGet(global::KnockOff.Called.AtLeastOnce);");
            w.Line();

            w.Line("\t\t\t/// <summary>Verifies getter access count satisfies the Called constraint. Throws VerificationException if not.</summary>");
            w.Line("\t\t\tpublic void VerifyGet(global::KnockOff.Called times)");
            w.Line("\t\t\t{");
            w.Line("\t\t\t\tif (!times.Validate(_getCount))");
            w.Line($"\t\t\t\t\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"{indexer.IndexerName} (get)\", times, _getCount));");
            w.Line("\t\t\t}");
            w.Line();
        }

        // VerifySet methods
        if (indexer.HasSetter)
        {
            w.Line("\t\t\t/// <summary>Verifies the setter was accessed at least once. Throws VerificationException if not.</summary>");
            w.Line("\t\t\tpublic void VerifySet() => VerifySet(global::KnockOff.Called.AtLeastOnce);");
            w.Line();

            w.Line("\t\t\t/// <summary>Verifies setter access count satisfies the Called constraint. Throws VerificationException if not.</summary>");
            w.Line("\t\t\tpublic void VerifySet(global::KnockOff.Called times)");
            w.Line("\t\t\t{");
            w.Line("\t\t\t\tif (!times.Validate(_setCount))");
            w.Line($"\t\t\t\t\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"{indexer.IndexerName} (set)\", times, _setCount));");
            w.Line("\t\t\t}");
            w.Line();
        }

        // Internal verification support for stub-level Verify/VerifyAll
        w.Line("\t\t\t/// <summary>Whether this indexer was marked with Verifiable().</summary>");
        w.Line("\t\t\tinternal bool IsVerifiable => _isVerifiable;");
        w.Line();

        w.Line("\t\t\t/// <summary>Whether this indexer has been configured (callbacks registered).</summary>");
        w.Line("\t\t\tinternal bool IsConfigured => _configured;");
        w.Line();

        w.Line("\t\t\t/// <summary>Checks verification for Stub.Verify() - only checks if marked verifiable.</summary>");
        w.Line("\t\t\tinternal global::KnockOff.VerificationFailure? CheckVerification()");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tif (!_isVerifiable) return null;");
        w.Line("\t\t\t\tvar times = _verifiableTimes ?? global::KnockOff.Called.AtLeastOnce;");
        w.Line($"\t\t\t\tvar totalCount = {totalCountExpr};");
        w.Line($"\t\t\t\treturn times.Validate(totalCount) ? null : new global::KnockOff.VerificationFailure(\"{indexer.IndexerName}\", times, totalCount);");
        w.Line("\t\t\t}");
        w.Line();

        w.Line("\t\t\t/// <summary>Checks verification for Stub.VerifyAll() - checks if configured.</summary>");
        w.Line("\t\t\tinternal global::KnockOff.VerificationFailure? CheckVerificationAll()");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tif (!IsConfigured) return null;");
        w.Line($"\t\t\t\tvar totalCount = {totalCountExpr};");
        w.Line($"\t\t\t\treturn totalCount >= 1 ? null : new global::KnockOff.VerificationFailure(\"{indexer.IndexerName}\", global::KnockOff.Called.AtLeastOnce, totalCount);");
        w.Line("\t\t\t}");

        w.Line("\t\t}");
        w.Line();
    }

    private static void RenderIndexerContainerClass(CodeWriter w, InlineIndexerGroup group)
    {
        // Deduplicate by KeyTypeFriendlyName - same key type shares the same interceptor in container
        var uniqueByKeyType = group.Indexers
            .GroupBy(i => i.KeyTypeFriendlyName)
            .Select(g => g.First())
            .ToList();

        w.Line($"\t\t/// <summary>Container for indexer interceptors with OfXxx access pattern.</summary>");
        w.Line($"\t\tpublic sealed class {group.ContainerClassName}");
        w.Line("\t\t{");

        // Of{KeyType} properties (container owns its interceptors)
        foreach (var indexer in uniqueByKeyType)
        {
            w.Line($"\t\t\t/// <summary>Gets the interceptor for indexer with {indexer.KeyTypeFriendlyName} key type.</summary>");
            w.Line($"\t\t\tpublic {indexer.InterceptorClassName}{indexer.TypeParameterList} Of{indexer.KeyTypeFriendlyName} {{ get; }} = new();");
            w.Line();
        }

        // Reset method (resets all)
        w.Line("\t\t\t/// <summary>Resets all indexer interceptors.</summary>");
        w.Line("\t\t\tpublic void Reset()");
        w.Line("\t\t\t{");
        foreach (var indexer in uniqueByKeyType)
        {
            w.Line($"\t\t\t\tOf{indexer.KeyTypeFriendlyName}.Reset();");
        }
        w.Line("\t\t\t}");
        w.Line();

        // Internal verification support for stub-level Verify/VerifyAll
        // Container aggregates verification from all indexer interceptors
        w.Line("\t\t\tinternal bool IsVerifiable => false; // Container is not individually verifiable");

        // Check if any contained interceptor is configured
        var isConfiguredParts = uniqueByKeyType.Select(i => $"Of{i.KeyTypeFriendlyName}.IsConfigured").ToList();
        w.Line($"\t\t\tinternal bool IsConfigured => {string.Join(" || ", isConfiguredParts)};");
        w.Line();

        w.Line("\t\t\t/// <summary>Checks verification for Stub.Verify() - only checks if marked verifiable.</summary>");
        w.Line("\t\t\tinternal global::KnockOff.VerificationFailure? CheckVerification()");
        w.Line("\t\t\t{");
        // Container returns first failure from any contained interceptor
        foreach (var indexer in uniqueByKeyType)
        {
            w.Line($"\t\t\t\tif (Of{indexer.KeyTypeFriendlyName}.CheckVerification() is {{ }} failure{indexer.KeyTypeFriendlyName}) return failure{indexer.KeyTypeFriendlyName};");
        }
        w.Line("\t\t\t\treturn null;");
        w.Line("\t\t\t}");
        w.Line();

        w.Line("\t\t\t/// <summary>Checks verification for Stub.VerifyAll() - checks if configured.</summary>");
        w.Line("\t\t\tinternal global::KnockOff.VerificationFailure? CheckVerificationAll()");
        w.Line("\t\t\t{");
        // Container returns first failure from any contained interceptor
        foreach (var indexer in uniqueByKeyType)
        {
            w.Line($"\t\t\t\tif (Of{indexer.KeyTypeFriendlyName}.CheckVerificationAll() is {{ }} failure{indexer.KeyTypeFriendlyName}) return failure{indexer.KeyTypeFriendlyName};");
        }
        w.Line("\t\t\t\treturn null;");
        w.Line("\t\t\t}");

        w.Line("\t\t}");
        w.Line();
    }

    // NOTE: RenderMethodInterceptorClass has been removed.
    // Method interceptors now use the shared MethodInterceptorRenderer.RenderInterceptorClass.

    private static void RenderGenericMethodHandler(CodeWriter w, InlineGenericMethodHandlerModel handler)
    {
        var ifaceTypeParamList = handler.InterfaceTypeParameterList;
        var ifaceConstraintClause = handler.InterfaceConstraintClauses;
        var isMultiArity = handler.ArityGroups.Count > 1;
        // When there's only one arity group, no suffix needed (even for multi-type-param methods like Convert<TIn, TOut>)
        // When there are multiple arity groups, use _N suffix to disambiguate dictionaries
        string GetDictSuffix(int typeParamCount) => isMultiArity ? $"_{typeParamCount}" : "";

        w.Line($"\t\t/// <summary>Interceptor for {handler.MethodName}.</summary>");
        w.Line($"\t\tpublic sealed class {handler.InterceptorClassName}{ifaceTypeParamList}{ifaceConstraintClause}");
        w.Line("\t\t{");

        // Each type arity gets its own dictionary
        foreach (var arity in handler.ArityGroups)
        {
            var dictSuffix = GetDictSuffix(arity.TypeParameterCount);
            w.Line($"\t\t\tprivate readonly global::System.Collections.Generic.Dictionary<{arity.KeyType}, object> _typedHandlers{dictSuffix} = new();");
        }
        w.Line();

        // Of<T>() method for each type arity
        foreach (var arity in handler.ArityGroups)
        {
            var dictSuffix = GetDictSuffix(arity.TypeParameterCount);
            w.Line($"\t\t\t/// <summary>Gets the typed handler for the specified type argument(s).</summary>");
            w.Line($"\t\t\tpublic {arity.TypedHandlerClassName}<{arity.TypeParameterNames}> Of<{arity.TypeParameterNames}>(){arity.ConstraintClauses}");
            w.Line("\t\t\t{");
            w.Line($"\t\t\t\tvar key = {arity.KeyConstruction};");
            w.Line($"\t\t\t\tif (!_typedHandlers{dictSuffix}.TryGetValue(key, out var handler))");
            w.Line("\t\t\t\t{");
            w.Line($"\t\t\t\t\thandler = new {arity.TypedHandlerClassName}<{arity.TypeParameterNames}>();");
            w.Line($"\t\t\t\t\t_typedHandlers{dictSuffix}[key] = handler;");
            w.Line("\t\t\t\t}");
            w.Line($"\t\t\t\treturn ({arity.TypedHandlerClassName}<{arity.TypeParameterNames}>)handler;");
            w.Line("\t\t\t}");
            w.Line();
        }

        // Aggregate tracking (private - use Verify for public API)
        if (!isMultiArity)
        {
            w.Line("\t\t\tprivate int TotalCallCount => _typedHandlers.Values.Cast<IGenericMethodCallTracker>().Sum(h => h.CallCount);");
        }
        else
        {
            var dictNames = string.Join(".Concat(", handler.ArityGroups.Select((a, i) =>
                $"_typedHandlers{GetDictSuffix(a.TypeParameterCount)}.Values"));
            dictNames += string.Join("", Enumerable.Range(0, handler.ArityGroups.Count - 1).Select(_ => ")"));
            w.Line($"\t\t\tprivate int TotalCallCount => {dictNames}.Cast<IGenericMethodCallTracker>().Sum(h => h.CallCount);");
        }
        w.Line();

        // CalledTypeArguments - only for single-arity, too complex for mixed
        if (!isMultiArity)
        {
            var arity = handler.ArityGroups.First();
            w.Line($"\t\t\t/// <summary>All type argument(s) that were used in calls.</summary>");
            w.Line($"\t\t\tpublic global::System.Collections.Generic.IReadOnlyList<{arity.KeyType}> CalledTypeArguments => _typedHandlers.Where(kvp => ((IGenericMethodCallTracker)kvp.Value).CallCount > 0).Select(kvp => kvp.Key).ToList();");
            w.Line();
        }

        // IsConfigured check across all dictionaries
        if (!isMultiArity)
        {
            w.Line("\t\t\tinternal bool IsConfigured => _typedHandlers.Count > 0;");
        }
        else
        {
            var configChecks = string.Join(" || ", handler.ArityGroups.Select(a =>
                $"_typedHandlers{GetDictSuffix(a.TypeParameterCount)}.Count > 0"));
            w.Line($"\t\t\tinternal bool IsConfigured => {configChecks};");
        }

        // Reset method - clears tracking state but preserves configuration (typed handlers with Return/Call)
        w.Line("\t\t\t/// <summary>Resets tracking state (call counts) but preserves configuration (Return/Call callbacks).</summary>");
        w.Line("\t\t\tpublic void Reset()");
        w.Line("\t\t\t{");
        foreach (var arity in handler.ArityGroups)
        {
            var dictSuffix = GetDictSuffix(arity.TypeParameterCount);
            w.Line($"\t\t\t\tforeach (var handler in _typedHandlers{dictSuffix}.Values.Cast<IResettable>())");
            w.Line("\t\t\t\t\thandler.Reset();");
        }
        w.Line("\t\t\t}");
        w.Line();

        // Verify methods
        w.Line("\t\t\t/// <summary>Verifies method was called at least once with any type argument. Throws VerificationException if not.</summary>");
        w.Line("\t\t\tpublic void Verify() => Verify(global::KnockOff.Called.AtLeastOnce);");
        w.Line();

        w.Line("\t\t\t/// <summary>Verifies total call count satisfies the Called constraint. Throws VerificationException if not.</summary>");
        w.Line("\t\t\tpublic void Verify(global::KnockOff.Called times)");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tif (!times.Validate(TotalCallCount))");
        w.Line($"\t\t\t\t\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"{handler.MethodName}\", times, TotalCallCount));");
        w.Line("\t\t\t}");
        w.Line();

        // Internal verification support for stub-level Verify/VerifyAll
        // Generic method handlers aggregate verification from all typed handlers
        w.Line("\t\t\tinternal bool IsVerifiable => false; // Generic handlers are not individually verifiable");
        w.Line();

        w.Line("\t\t\t/// <summary>Checks verification for Stub.Verify() - only checks if marked verifiable.</summary>");
        w.Line("\t\t\tinternal global::KnockOff.VerificationFailure? CheckVerification() => null; // Generic methods not individually verifiable");
        w.Line();

        w.Line("\t\t\t/// <summary>Checks verification for Stub.VerifyAll() - checks if configured.</summary>");
        w.Line("\t\t\tinternal global::KnockOff.VerificationFailure? CheckVerificationAll()");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tif (!IsConfigured) return null;");
        w.Line($"\t\t\t\treturn TotalCallCount >= 1 ? null : new global::KnockOff.VerificationFailure(\"{handler.MethodName}\", global::KnockOff.Called.AtLeastOnce, TotalCallCount);");
        w.Line("\t\t\t}");
        w.Line();

        // Nested Typed Handler Classes (one per type arity)
        foreach (var arity in handler.ArityGroups)
        {
            RenderInlineTypedHandlerClass(w, handler.MethodName, arity);
        }

        w.Line("\t\t}");
        w.Line();
    }

    private static void RenderInlineTypedHandlerClass(CodeWriter w, string methodName, InlineGenericTypeArityGroup arity)
    {
        w.Line($"\t\t\t/// <summary>Typed handler for {methodName} with specific type arguments.</summary>");
        w.Line($"\t\t\tpublic sealed class {arity.TypedHandlerClassName}<{arity.TypeParameterNames}> : IGenericMethodCallTracker, IResettable, global::KnockOff.IMethodTracking{arity.ConstraintClauses}");
        w.Line("\t\t\t{");

        // Delegate
        w.Line($"\t\t\t\t/// <summary>Delegate for {methodName}.</summary>");
        w.Line($"\t\t\t\t{arity.DelegateSignature}");
        w.Line();

        // Private callback field
        w.Line($"\t\t\t\tprivate {methodName}Delegate? _call;");
        w.Line();

        // CallCount - private field with explicit interface implementation for aggregation
        w.Line("\t\t\t\tprivate int _callCount;");
        w.Line("\t\t\t\tint IGenericMethodCallTracker.CallCount => _callCount;");
        w.Line();

        // LastArg/LastArgs
        if (arity.LastCallArgType != null)
        {
            var param = arity.NonGenericParameters.GetArray()![0];
            w.Line($"\t\t\t\t/// <summary>The '{param.Name}' argument from the most recent call.</summary>");
            w.Line($"\t\t\t\tpublic {arity.LastCallArgType} LastArg {{ get; private set; }}");
            w.Line();
        }
        else if (arity.LastCallArgsType != null)
        {
            w.Line("\t\t\t\t/// <summary>The arguments from the most recent call.</summary>");
            w.Line($"\t\t\t\tpublic {arity.LastCallArgsType} LastArgs {{ get; private set; }}");
            w.Line();
        }

        // Return/Call method (returns IMethodTracking for consistency with regular method interceptors)
        var typedHandlerEntryPoint = arity.IsVoid ? "Call" : "Return";
        w.Line("\t\t\t\t/// <summary>Sets the callback invoked when this method is called. Returns this handler for tracking.</summary>");
        w.Line($"\t\t\t\tpublic global::KnockOff.IMethodTracking {typedHandlerEntryPoint}({methodName}Delegate callback) {{ _call = callback; return this; }}");
        w.Line();

        // Callback property for internal use by invocation logic
        w.Line("\t\t\t\t/// <summary>Gets the configured callback (internal use).</summary>");
        w.Line($"\t\t\t\tinternal {methodName}Delegate? Callback => _call;");
        w.Line();

        // RecordCall
        w.Line("\t\t\t\t/// <summary>Records a method call.</summary>");
        if (arity.NonGenericParameters.Count == 0)
        {
            w.Line("\t\t\t\tpublic void RecordCall() => _callCount++;");
        }
        else if (arity.NonGenericParameters.Count == 1)
        {
            var param = arity.NonGenericParameters.GetArray()![0];
            w.Line($"\t\t\t\tpublic void RecordCall({param.Type} {param.Name}) {{ _callCount++; LastArg = {param.Name}; }}");
        }
        else
        {
            var paramList = string.Join(", ", arity.NonGenericParameters.Select(p => $"{p.Type} {p.Name}"));
            var tupleConstruction = string.Join(", ", arity.NonGenericParameters.Select(p => p.Name));
            w.Line($"\t\t\t\tpublic void RecordCall({paramList}) {{ _callCount++; LastArgs = ({tupleConstruction}); }}");
        }
        w.Line();

        // Reset - clears tracking state but preserves configuration (Return/Call callback)
        w.Line("\t\t\t\t/// <summary>Resets tracking state (_callCount, LastArg/LastArgs) but preserves configuration (Return/Call).</summary>");
        if (arity.NonGenericParameters.Count == 0)
        {
            w.Line("\t\t\t\tpublic void Reset() { _callCount = 0; }");
        }
        else if (arity.NonGenericParameters.Count == 1)
        {
            w.Line("\t\t\t\tpublic void Reset() { _callCount = 0; LastArg = default; }");
        }
        else
        {
            w.Line("\t\t\t\tpublic void Reset() { _callCount = 0; LastArgs = default; }");
        }
        w.Line();

        // Verify methods - new API throws VerificationException
        w.Line("\t\t\t\t/// <summary>Verifies call count is at least once. Throws VerificationException if not.</summary>");
        w.Line("\t\t\t\tpublic void Verify() => Verify(global::KnockOff.Called.AtLeastOnce);");
        w.Line();

        w.Line("\t\t\t\t/// <summary>Verifies call count satisfies the Called constraint. Throws VerificationException if not.</summary>");
        w.Line("\t\t\t\tpublic void Verify(global::KnockOff.Called times)");
        w.Line("\t\t\t\t{");
        w.Line("\t\t\t\t\tif (!times.Validate(_callCount))");
        w.Line("\t\t\t\t\t\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"method\", times, _callCount));");
        w.Line("\t\t\t\t}");
        w.Line();

        // Verifiable methods
        w.Line("\t\t\t\t/// <summary>Marks for verification by Stub.Verify(). Returns this for fluent chaining.</summary>");
        w.Line("\t\t\t\tpublic global::KnockOff.IMethodTracking Verifiable() => this;");
        w.Line();

        w.Line("\t\t\t\t/// <summary>Marks for verification by Stub.Verify() with Called constraint. Returns this for fluent chaining.</summary>");
        w.Line("\t\t\t\tpublic global::KnockOff.IMethodTracking Verifiable(global::KnockOff.Called times) => this;");

        w.Line("\t\t\t}");
    }

    private static void RenderEventInterceptorClass(CodeWriter w, InlineEventModel evt, string stubClassName)
    {
        var typeParamList = evt.TypeParameterList;
        var constraintClause = evt.ConstraintClauses;

        w.Line($"\t\t/// <summary>Interceptor for {stubClassName}.{evt.EventName} event.</summary>");
        w.Line($"\t\tpublic sealed class {evt.InterceptorClassName}{typeParamList}{constraintClause}");
        w.Line("\t\t{");

        // Backing field
        w.Line($"\t\t\tprivate {evt.DelegateType}? _handler;");
        w.Line();

        // Add/Remove tracking
        w.Line("\t\t\tprivate int _addCount;");
        w.Line("\t\t\tprivate int _removeCount;");
        w.Line();

        w.Line("\t\t\t/// <summary>Whether any handlers are subscribed.</summary>");
        w.Line("\t\t\tpublic bool HasSubscribers => _handler != null;");
        w.Line();

        w.Line("\t\t\t/// <summary>Records an event subscription.</summary>");
        w.Line($"\t\t\tpublic void RecordAdd({evt.DelegateType}? value) {{ _addCount++; _handler = ({evt.DelegateType}?)global::System.Delegate.Combine(_handler, value); }}");
        w.Line();
        w.Line("\t\t\t/// <summary>Records an event unsubscription.</summary>");
        w.Line($"\t\t\tpublic void RecordRemove({evt.DelegateType}? value) {{ _removeCount++; _handler = ({evt.DelegateType}?)global::System.Delegate.Remove(_handler, value); }}");
        w.Line();

        // Raise method
        RenderEventRaiseMethod(w, evt, "\t\t\t");

        w.Line("\t\t\t/// <summary>Resets tracking state (counts, handler) but preserves verifiable marking.</summary>");
        w.Line("\t\t\tpublic void Reset() { _addCount = 0; _removeCount = 0; _handler = null; }");
        w.Line();

        // Verification API for events
        w.Line("\t\t\tprivate bool _isVerifiable;");
        w.Line("\t\t\tprivate global::KnockOff.Called? _verifiableTimes;");
        w.Line();

        w.Line("\t\t\t/// <summary>Verifies the event was subscribed to at least once.</summary>");
        w.Line("\t\t\tpublic void VerifyAdd() => VerifyAdd(global::KnockOff.Called.AtLeastOnce);");
        w.Line();

        w.Line("\t\t\t/// <summary>Verifies the event subscription count matches the Called constraint.</summary>");
        w.Line("\t\t\tpublic void VerifyAdd(global::KnockOff.Called times)");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tif (!times.Validate(_addCount))");
        w.Line($"\t\t\t\t\tthrow new global::KnockOff.VerificationException($\"Event '{evt.EventName}' add verification failed: expected {{times}}, but was called {{_addCount}} time(s).\");");
        w.Line("\t\t\t}");
        w.Line();

        w.Line("\t\t\t/// <summary>Verifies the event was unsubscribed at least once.</summary>");
        w.Line("\t\t\tpublic void VerifyRemove() => VerifyRemove(global::KnockOff.Called.AtLeastOnce);");
        w.Line();

        w.Line("\t\t\t/// <summary>Verifies the event unsubscription count matches the Called constraint.</summary>");
        w.Line("\t\t\tpublic void VerifyRemove(global::KnockOff.Called times)");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tif (!times.Validate(_removeCount))");
        w.Line($"\t\t\t\t\tthrow new global::KnockOff.VerificationException($\"Event '{evt.EventName}' remove verification failed: expected {{times}}, but was called {{_removeCount}} time(s).\");");
        w.Line("\t\t\t}");
        w.Line();

        w.Line("\t\t\t/// <summary>Verifies the event was accessed (add or remove) at least once.</summary>");
        w.Line("\t\t\tpublic void Verify() => Verify(global::KnockOff.Called.AtLeastOnce);");
        w.Line();

        w.Line("\t\t\t/// <summary>Verifies the total event access count matches the Called constraint.</summary>");
        w.Line("\t\t\tpublic void Verify(global::KnockOff.Called times)");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tvar totalCount = _addCount + _removeCount;");
        w.Line("\t\t\t\tif (!times.Validate(totalCount))");
        w.Line($"\t\t\t\t\tthrow new global::KnockOff.VerificationException($\"Event '{evt.EventName}' verification failed: expected {{times}}, but was called {{totalCount}} time(s).\");");
        w.Line("\t\t\t}");
        w.Line();

        w.Line("\t\t\t/// <summary>Marks this event for verification by Stub.Verify(). Returns this for fluent chaining.</summary>");
        w.Line($"\t\t\tpublic {evt.InterceptorClassName}{typeParamList} Verifiable()");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\t_isVerifiable = true;");
        w.Line("\t\t\t\t_verifiableTimes = global::KnockOff.Called.AtLeastOnce;");
        w.Line("\t\t\t\treturn this;");
        w.Line("\t\t\t}");
        w.Line();

        w.Line("\t\t\t/// <summary>Marks this event for verification by Stub.Verify() with Called constraint. Returns this for fluent chaining.</summary>");
        w.Line($"\t\t\tpublic {evt.InterceptorClassName}{typeParamList} Verifiable(global::KnockOff.Called times)");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\t_isVerifiable = true;");
        w.Line("\t\t\t\t_verifiableTimes = times;");
        w.Line("\t\t\t\treturn this;");
        w.Line("\t\t\t}");
        w.Line();

        // Internal verification methods for stub-level Verify()/VerifyAll()
        w.Line("\t\t\tinternal bool IsVerifiable => _isVerifiable;");
        w.Line("\t\t\tinternal bool IsConfigured => _handler != null;");
        w.Line();

        w.Line("\t\t\t/// <summary>Checks verification for Stub.Verify() - only verifiable items.</summary>");
        w.Line("\t\t\tinternal global::KnockOff.VerificationFailure? CheckVerification()");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tif (!_isVerifiable) return null;");
        w.Line("\t\t\t\tvar times = _verifiableTimes ?? global::KnockOff.Called.AtLeastOnce;");
        w.Line("\t\t\t\tvar totalCount = _addCount + _removeCount;");
        w.Line("\t\t\t\tif (!times.Validate(totalCount))");
        w.Line($"\t\t\t\t\treturn new global::KnockOff.VerificationFailure(\"{evt.EventName}\", times, totalCount);");
        w.Line("\t\t\t\treturn null;");
        w.Line("\t\t\t}");
        w.Line();

        w.Line("\t\t\t/// <summary>Checks verification for Stub.VerifyAll() - all configured items.</summary>");
        w.Line("\t\t\tinternal global::KnockOff.VerificationFailure? CheckVerificationAll()");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tif (!IsConfigured && !_isVerifiable) return null;");
        w.Line("\t\t\t\tvar times = _verifiableTimes ?? global::KnockOff.Called.AtLeastOnce;");
        w.Line("\t\t\t\tvar totalCount = _addCount + _removeCount;");
        w.Line("\t\t\t\tif (!times.Validate(totalCount))");
        w.Line($"\t\t\t\t\treturn new global::KnockOff.VerificationFailure(\"{evt.EventName}\", times, totalCount);");
        w.Line("\t\t\t\treturn null;");
        w.Line("\t\t\t}");

        w.Line("\t\t}");
        w.Line();
    }

    private static void RenderEventRaiseMethod(CodeWriter w, InlineEventModel evt, string indent)
    {
        if (evt.RaiseReturnsValue)
        {
            // Func-style delegate
            w.Line($"{indent}/// <summary>Raises the event with the specified arguments and returns the result.</summary>");
            if (string.IsNullOrEmpty(evt.RaiseParameters))
            {
                w.Line($"{indent}public {evt.RaiseReturnType} Raise() => _handler != null ? _handler.Invoke() : default!;");
            }
            else
            {
                w.Line($"{indent}public {evt.RaiseReturnType} Raise({evt.RaiseParameters}) => _handler != null ? _handler.Invoke({evt.RaiseArguments}) : default!;");
            }
        }
        else if (evt.UsesDynamicInvoke)
        {
            // Custom delegate - use DynamicInvoke
            if (string.IsNullOrEmpty(evt.RaiseParameters))
            {
                w.Line($"{indent}/// <summary>Raises the event.</summary>");
                w.Line($"{indent}public void Raise() => (_handler as global::System.Action)?.Invoke();");
            }
            else
            {
                w.Line($"{indent}/// <summary>Invokes the handler if subscribed.</summary>");
                w.Line($"{indent}public void Raise({evt.RaiseParameters}) => _handler?.DynamicInvoke({evt.RaiseArguments});");
            }
        }
        else
        {
            // Standard Action/EventHandler
            if (string.IsNullOrEmpty(evt.RaiseParameters))
            {
                w.Line($"{indent}/// <summary>Raises the event.</summary>");
                w.Line($"{indent}public void Raise() => _handler?.Invoke();");
            }
            else
            {
                w.Line($"{indent}/// <summary>Raises the event with the specified arguments.</summary>");
                w.Line($"{indent}public void Raise({evt.RaiseParameters}) => _handler?.Invoke({evt.RaiseArguments});");
            }
        }
        w.Line();
    }

    private static void RenderSmartDefaultMethod(CodeWriter w)
    {
        w.Line("\t\t\t/// <summary>Gets a smart default value for a generic type at runtime.</summary>");
        w.Line("\t\t\tprivate static TSmartDefault SmartDefault<TSmartDefault>(string methodName)");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tvar type = typeof(TSmartDefault);");
        w.Line();
        w.Line("\t\t\t\t// Value types -> default(TSmartDefault)");
        w.Line("\t\t\t\tif (type.IsValueType)");
        w.Line("\t\t\t\t\treturn default!;");
        w.Line();
        w.Line("\t\t\t\t// Check for parameterless constructor");
        w.Line("\t\t\t\tvar ctor = type.GetConstructor(");
        w.Line("\t\t\t\t\tSystem.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Instance,");
        w.Line("\t\t\t\t\tnull, System.Type.EmptyTypes, null);");
        w.Line();
        w.Line("\t\t\t\tif (ctor != null)");
        w.Line("\t\t\t\t\treturn (TSmartDefault)ctor.Invoke(null);");
        w.Line();
        w.Line("\t\t\t\tthrow new global::System.InvalidOperationException(");
        w.Line("\t\t\t\t\t$\"No implementation provided for {methodName}<{type.Name}>. \" +");
        w.Line("\t\t\t\t\t$\"Set the handler's Return or Call.\");");
        w.Line("\t\t\t}");
        w.Line();
    }

