    #region Implementation Rendering

    private static void RenderImplementation(
        CodeWriter w,
        InlineInterfaceImplementation impl,
        Dictionary<string, string> preCompiledInterceptors,
        Dictionary<string, UnifiedMethodInterceptorModel> compositorGroups)
    {
        switch (impl.Kind)
        {
            case InlineMemberKind.Property:
                RenderPropertyImplementation(w, impl);
                break;
            case InlineMemberKind.Indexer:
                RenderIndexerImplementation(w, impl);
                break;
            case InlineMemberKind.Method:
                RenderMethodImplementation(w, impl, preCompiledInterceptors, compositorGroups);
                break;
            case InlineMemberKind.Event:
                RenderEventImplementation(w, impl);
                break;
        }
    }

    private static void RenderPropertyImplementation(CodeWriter w, InlineInterfaceImplementation impl)
    {
        if (impl.DelegationTarget != null)
        {
            // Delegation implementation
            w.Line($"\t\t\t{impl.ReturnType} {impl.InterfaceFullName}.{impl.MemberName}");
            w.Line("\t\t\t{");
            if (impl.HasGetter)
            {
                w.Line($"\t\t\t\tget => (({impl.DelegationTarget.TargetInterfaceFullName})this).{impl.DelegationTarget.TargetMemberName};");
            }
            if (impl.HasSetter)
            {
                w.Line($"\t\t\t\tset => (({impl.DelegationTarget.TargetInterfaceFullName})this).{impl.DelegationTarget.TargetMemberName} = ({impl.DelegationTarget.TargetReturnType})value;");
            }
            w.Line("\t\t\t}");
            w.Line();
            return;
        }

        w.Line($"\t\t\t{impl.RefReturnPrefix}{impl.ReturnType} {impl.InterfaceFullName}.{impl.MemberName}");
        w.Line("\t\t\t{");

        if (impl.IsRefReturn)
        {
            // Ref return properties are always get-only (C# constraint)
            w.Line("\t\t\t\tget");
            w.Line("\t\t\t\t{");
            w.Line($"\t\t\t\t\t{impl.InterceptorName}.InvokeRefGet(Strict);");
            w.Line($"\t\t\t\t\treturn ref {impl.InterceptorName}._refReturnBacking;");
            w.Line("\t\t\t\t}");
        }
        else if (impl.HasGetter)
        {
            if (impl.IsInitOnly)
            {
                // Init-only: use InvokeGet which handles the priority chain
                w.Line($"\t\t\t\tget => {impl.InterceptorName}.InvokeGet(Strict);");
            }
            else
            {
                // Regular: use InvokeGet which handles the priority chain
                w.Line($"\t\t\t\tget => {impl.InterceptorName}.InvokeGet(Strict);");
            }
        }

        if (!impl.IsRefReturn && impl.HasSetter)
        {
            var setterKeyword = impl.IsInitOnly ? "init" : "set";
            if (impl.SetterPragmaDisable != null)
                w.Append(impl.SetterPragmaDisable);
            if (impl.IsInitOnly)
            {
                // Init-only: record and set value via SetValue (no InvokeSet for init accessor)
                w.Line($"\t\t\t\t{setterKeyword} {{ {impl.InterceptorName}.RecordSet(value); {impl.InterceptorName}.SetValue(value); }}");
            }
            else
            {
                // Regular: use InvokeSet which handles the priority chain
                w.Line($"\t\t\t\t{setterKeyword} => {impl.InterceptorName}.InvokeSet(Strict, value);");
            }
            if (impl.SetterPragmaRestore != null)
                w.Line(impl.SetterPragmaRestore);
        }

        w.Line("\t\t\t}");
        w.Line();
    }

    private static void RenderIndexerImplementation(CodeWriter w, InlineInterfaceImplementation impl)
    {
        var invokeSuffix = impl.InvokeSuffix;

        w.Line($"\t\t\t{impl.RefReturnPrefix}{impl.ReturnType} {impl.InterfaceFullName}.this[{impl.ParameterDeclarations}]");
        w.Line("\t\t\t{");

        if (impl.IsRefReturn)
        {
            // Ref return indexers are always get-only (C# constraint)
            w.Line("\t\t\t\tget");
            w.Line("\t\t\t\t{");
            w.Line($"\t\t\t\t\t{impl.InterceptorName}.InvokeRefGet{invokeSuffix}(Strict, {impl.ArgumentList});");
            w.Line($"\t\t\t\t\treturn ref {impl.InterceptorName}._refReturnBacking{invokeSuffix};");
            w.Line("\t\t\t\t}");
        }
        else
        {
            if (impl.HasGetter)
            {
                // Use InvokeGet which handles the priority chain
                w.Line($"\t\t\t\tget => {impl.InterceptorName}.InvokeGet{invokeSuffix}(Strict, {impl.ArgumentList});");
            }

            if (impl.HasSetter)
            {
                // Use InvokeSet which handles the priority chain
                var setterKeyword = impl.IsInitOnly ? "init" : "set";
                w.Line($"\t\t\t\t{setterKeyword} => {impl.InterceptorName}.InvokeSet{invokeSuffix}(Strict, {impl.ArgumentList}, value);");
            }
        }

        w.Line("\t\t\t}");
        w.Line();
    }

    private static void RenderMethodImplementation(
        CodeWriter w,
        InlineInterfaceImplementation impl,
        Dictionary<string, string> preCompiledInterceptors,
        Dictionary<string, UnifiedMethodInterceptorModel> compositorGroups)
    {
        if (impl.DelegationTarget != null)
        {
            // Delegation implementation
            var returnKeyword = impl.IsVoid ? "" : "return ";
            w.Line($"\t\t\t{impl.ReturnType} {impl.InterfaceFullName}.{impl.MemberName}({impl.ParameterDeclarations})");
            w.Line("\t\t\t{");
            w.Line($"\t\t\t\t{returnKeyword}(({impl.DelegationTarget.TargetInterfaceFullName})this).{impl.DelegationTarget.TargetMemberName}({impl.DelegationTarget.CastArguments});");
            w.Line("\t\t\t}");
            w.Line();
            return;
        }

        if (impl.IsGenericMethod)
        {
            RenderGenericMethodImplementation(w, impl);
        }
        else
        {
            var isPreCompiled = preCompiledInterceptors.ContainsKey(impl.InterceptorName);
            var isCompositor = compositorGroups.ContainsKey(impl.InterceptorName);
            RenderNonGenericMethodImplementation(w, impl, isPreCompiled, isCompositor ? compositorGroups[impl.InterceptorName] : null);
        }
    }

    private static void RenderNonGenericMethodImplementation(
        CodeWriter w,
        InlineInterfaceImplementation impl,
        bool isPreCompiled,
        UnifiedMethodInterceptorModel? compositorModel)
    {
        w.Line($"\t\t\t{impl.RefReturnPrefix}{impl.ReturnType} {impl.InterfaceFullName}.{impl.MemberName}({impl.ParameterDeclarations})");
        w.Line("\t\t\t{");

        if (isPreCompiled)
        {
            // Pre-compiled interceptor: use GetMethodInvokeExpression for proper ValueTask wrapping
            // Strip ref/in prefixes from argument list (pre-compiled interceptors use plain parameters)
            var cleanArgs = StripRefPrefixes(impl.ArgumentList);
            // TTuple types: wrap 2+ params in tuple literal for Invoke(bool strict, TArgs args)
            var wrappedArgs = PreCompiledInterceptorRenderer.WrapInvokeArgs(cleanArgs);
            var invokeArgs = string.IsNullOrEmpty(wrappedArgs)
                ? "Strict"
                : $"Strict{wrappedArgs}";

            // Detect ValueTask wrapping needs
            var (_, _, isAsyncValueTaskT) = PreCompiledInterceptorRenderer.GetAsyncTypeInfoPublic(impl.ReturnType);
            var (_, isVoidValueTask) = PreCompiledInterceptorRenderer.GetVoidAsyncInfoPublic(impl.ReturnType);

            if (impl.IsVoid)
            {
                w.Line($"\t\t\t\t{impl.InterceptorName}.Invoke({invokeArgs});");
            }
            else if (isVoidValueTask)
            {
                w.Line($"\t\t\t\treturn new global::System.Threading.Tasks.ValueTask({impl.InterceptorName}.Invoke({invokeArgs}));");
            }
            else if (isAsyncValueTaskT)
            {
                w.Line($"\t\t\t\treturn new {impl.ReturnType}({impl.InterceptorName}.Invoke({invokeArgs}));");
            }
            else
            {
                w.Line($"\t\t\t\treturn {impl.InterceptorName}.Invoke({invokeArgs});");
            }
        }
        else if (compositorModel != null)
        {
            // Compositor: uses InvokeSuffix for overload disambiguation
            // Compositor Invoke methods already handle ValueTask wrapping,
            // so NO additional wrapping is needed here.
            var cleanArgs = StripRefPrefixes(impl.ArgumentList);
            // TTuple types: wrap 2+ params in tuple literal for Invoke(bool strict, TArgs args)
            var wrappedArgs = PreCompiledInterceptorRenderer.WrapInvokeArgs(cleanArgs);
            var invokeArgs = string.IsNullOrEmpty(wrappedArgs)
                ? "Strict"
                : $"Strict{wrappedArgs}";

            if (impl.IsVoid)
                w.Line($"\t\t\t\t{impl.InterceptorName}.Invoke{impl.InvokeSuffix}({invokeArgs});");
            else
                w.Line($"\t\t\t\treturn {impl.InterceptorName}.Invoke{impl.InvokeSuffix}({invokeArgs});");
        }
        else
        {
            // Fallback: generated interceptor class (original pattern)
            var invokeArgs = string.IsNullOrEmpty(impl.ArgumentList)
                ? "Strict"
                : $"Strict, {impl.ArgumentList}";

            if (impl.IsRefReturn)
            {
                var invokeRefSuffix = string.IsNullOrEmpty(impl.InvokeSuffix) ? "" : impl.InvokeSuffix;
                var backingField = string.IsNullOrEmpty(impl.InvokeSuffix) ? "_refReturnBacking" : $"_refReturnBacking{impl.InvokeSuffix}";
                w.Line($"\t\t\t\t{impl.InterceptorName}.InvokeRef{invokeRefSuffix}({invokeArgs});");
                w.Line($"\t\t\t\treturn ref {impl.InterceptorName}.{backingField};");
            }
            else if (impl.IsVoid)
                w.Line($"\t\t\t\t{impl.InterceptorName}.Invoke{impl.InvokeSuffix}({invokeArgs});");
            else
                w.Line($"\t\t\t\treturn {impl.InterceptorName}.Invoke{impl.InvokeSuffix}({invokeArgs});");
        }

        w.Line("\t\t\t}");
        w.Line();
    }

    /// <summary>
    /// Strips ref/in/out prefixes from an argument list string.
    /// Pre-compiled interceptors use plain parameters, not ref/in/out.
    /// </summary>
    private static string StripRefPrefixes(string argumentList)
    {
        if (string.IsNullOrEmpty(argumentList))
            return argumentList;

        var args = argumentList.Split(',');
        var cleanArgs = new List<string>();
        foreach (var arg in args)
        {
            var trimmed = arg.Trim();
            if (trimmed.StartsWith("in "))
                trimmed = trimmed.Substring(3);
            else if (trimmed.StartsWith("ref "))
                trimmed = trimmed.Substring(4);
            else if (trimmed.StartsWith("out "))
                trimmed = trimmed.Substring(4);
            cleanArgs.Add(trimmed);
        }
        return string.Join(", ", cleanArgs);
    }

    private static void RenderGenericMethodImplementation(CodeWriter w, InlineInterfaceImplementation impl)
    {
        // For methods with unconstrained nullable type parameters (T? without where T : class),
        // we must disable nullable context. Without this, the compiler interprets T? as Nullable<T>
        // (CS0453) or reports nullability mismatch (CS8769).
        if (impl.NeedsNullableDisable)
            w.Line("#nullable disable");

        w.Line($"\t\t\t{impl.ReturnType} {impl.InterfaceFullName}.{impl.MemberName}{impl.TypeParameterDecl}({impl.ParameterDeclarations}){impl.ConstraintClauses}");
        w.Line("\t\t\t{");

        // Initialize out parameters first
        foreach (var outParamInit in impl.OutParameterInitializations)
        {
            w.Line($"\t\t\t\t{outParamInit}");
        }

        // Get the typed handler via Of<T>()
        w.Line($"\t\t\t\tvar typedHandler = {impl.InterceptorName}{impl.OfTypeAccess};");

        // Record the call
        if (string.IsNullOrEmpty(impl.NonGenericArgList))
        {
            w.Line("\t\t\t\ttypedHandler.RecordCall();");
        }
        else
        {
            w.Line($"\t\t\t\ttypedHandler.RecordCall({impl.NonGenericArgList});");
        }

        // Check for Callback
        w.Line($"\t\t\t\tif (typedHandler.Callback is {{ }} callCallback)");
        if (impl.IsVoid)
        {
            w.Line($"\t\t\t\t{{ callCallback({impl.CallArgs}); return; }}");
        }
        else
        {
            w.Line($"\t\t\t\t\treturn callCallback({impl.CallArgs});");
        }

        // Strict mode check
        w.Line($"\t\t\t\tif (Strict) throw global::KnockOff.StubException.NotConfigured(\"{impl.SimpleInterfaceName}\", \"{impl.MemberName}\");");

        // Default behavior
        if (!impl.IsVoid)
        {
            // Check for Task/ValueTask types
            if (impl.ReturnType == "global::System.Threading.Tasks.Task")
            {
                w.Line("\t\t\t\treturn global::System.Threading.Tasks.Task.CompletedTask;");
            }
            else if (impl.ReturnType == "global::System.Threading.Tasks.ValueTask")
            {
                w.Line("\t\t\t\treturn default;");
            }
            else if (impl.IsNullable)
            {
                w.Line("\t\t\t\treturn default!;");
            }
            else
            {
                w.Line($"\t\t\t\treturn {impl.DefaultExpression};");
            }
        }

        w.Line("\t\t\t}");

        if (impl.NeedsNullableDisable)
            w.Line("#nullable restore");
        w.Line();
    }

