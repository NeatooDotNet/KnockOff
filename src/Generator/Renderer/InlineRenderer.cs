    private static void RenderGenericMethodHandler(CodeWriter w, InlineGenericMethodHandlerModel handler)
    {
        var ifaceTypeParamList = handler.InterfaceTypeParameterList;
        var ifaceConstraintClause = handler.InterfaceConstraintClauses;

        w.Line($"\t\t/// <summary>Interceptor for {handler.MethodName}.</summary>");
        w.Line($"\t\tpublic sealed class {handler.InterceptorClassName}{ifaceTypeParamList}{ifaceConstraintClause}");
        w.Line("\t\t{");

        // Dictionary for typed handlers
        w.Line($"\t\t\tprivate readonly global::System.Collections.Generic.Dictionary<{handler.KeyType}, object> _typedHandlers = new();");
        w.Line();

        // Of<T>() method
        w.Line($"\t\t\t/// <summary>Gets the typed handler for the specified type argument(s).</summary>");
        w.Line($"\t\t\tpublic {handler.TypedHandlerClassName}<{handler.TypeParameterNames}> Of<{handler.TypeParameterNames}>(){handler.MethodConstraintClauses}");
        w.Line("\t\t\t{");
        w.Line($"\t\t\t\tvar key = {handler.KeyConstruction};");
        w.Line($"\t\t\t\tif (!_typedHandlers.TryGetValue(key, out var handler))");
        w.Line("\t\t\t\t{");
        w.Line($"\t\t\t\t\thandler = new {handler.TypedHandlerClassName}<{handler.TypeParameterNames}>();");
        w.Line("\t\t\t\t\t_typedHandlers[key] = handler;");
        w.Line("\t\t\t\t}");
        w.Line($"\t\t\t\treturn ({handler.TypedHandlerClassName}<{handler.TypeParameterNames}>)handler;");
        w.Line("\t\t\t}");
        w.Line();

        // Aggregate tracking
        w.Line("\t\t\t/// <summary>Total number of calls across all type arguments.</summary>");
        w.Line("\t\t\tpublic int TotalCallCount => _typedHandlers.Values.Cast<IGenericMethodCallTracker>().Sum(h => h.CallCount);");
        w.Line();
        w.Line("\t\t\t/// <summary>True if this method was called with any type argument.</summary>");
        w.Line("\t\t\tpublic bool WasCalled => _typedHandlers.Values.Cast<IGenericMethodCallTracker>().Any(h => h.WasCalled);");
        w.Line();
        w.Line($"\t\t\t/// <summary>All type argument(s) that were used in calls.</summary>");
        w.Line($"\t\t\tpublic global::System.Collections.Generic.IReadOnlyList<{handler.KeyType}> CalledTypeArguments => _typedHandlers.Keys.ToList();");
        w.Line();

        // Reset method - clears tracking state but preserves configuration (typed handlers with OnCall)
        w.Line("\t\t\t/// <summary>Resets tracking state (call counts) but preserves configuration (OnCall callbacks).</summary>");
        w.Line("\t\t\tpublic void Reset()");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tforeach (var handler in _typedHandlers.Values.Cast<IResettable>())");
        w.Line("\t\t\t\t\thandler.Reset();");
        w.Line("\t\t\t}");
        w.Line();

        // Internal verification support for stub-level Verify/VerifyAll
        // Generic method handlers aggregate verification from all typed handlers
        w.Line("\t\t\tinternal bool IsVerifiable => false; // Generic handlers are not individually verifiable");
        w.Line("\t\t\tinternal bool IsConfigured => _typedHandlers.Count > 0;");
        w.Line();

        w.Line("\t\t\t/// <summary>Checks verification for Stub.Verify() - only checks if marked verifiable.</summary>");
        w.Line("\t\t\tinternal global::KnockOff.VerificationFailure? CheckVerification() => null; // Generic methods not individually verifiable");
        w.Line();

        w.Line("\t\t\t/// <summary>Checks verification for Stub.VerifyAll() - checks if configured.</summary>");
        w.Line("\t\t\tinternal global::KnockOff.VerificationFailure? CheckVerificationAll()");
        w.Line("\t\t\t{");
        w.Line("\t\t\t\tif (!IsConfigured) return null;");
        w.Line($"\t\t\t\treturn TotalCallCount >= 1 ? null : new global::KnockOff.VerificationFailure(\"{handler.MethodName}\", global::KnockOff.Times.AtLeastOnce, TotalCallCount);");
        w.Line("\t\t\t}");
        w.Line();

        // Nested Typed Handler Class
        RenderTypedHandlerClass(w, handler);

        w.Line("\t\t}");
        w.Line();
    }

    private static void RenderTypedHandlerClass(CodeWriter w, InlineGenericMethodHandlerModel handler)
    {
        w.Line($"\t\t\t/// <summary>Typed handler for {handler.MethodName} with specific type arguments.</summary>");
        w.Line($"\t\t\tpublic sealed class {handler.TypedHandlerClassName}<{handler.TypeParameterNames}> : IGenericMethodCallTracker, IResettable, global::KnockOff.IMethodTracking{handler.MethodConstraintClauses}");
        w.Line("\t\t\t{");

        // Delegate
        w.Line($"\t\t\t\t/// <summary>Delegate for {handler.MethodName}.</summary>");
        w.Line($"\t\t\t\t{handler.DelegateSignature}");
        w.Line();

        // Private callback field
        w.Line($"\t\t\t\tprivate {handler.MethodName}Delegate? _onCall;");
        w.Line();

        // CallCount
        w.Line("\t\t\t\t/// <summary>Number of times this method was called with these type arguments.</summary>");
        w.Line("\t\t\t\tpublic int CallCount { get; private set; }");
        w.Line();

        // LastCallArg/LastCallArgs
        if (handler.LastCallArgType != null)
        {
            var param = handler.NonGenericParameters.GetArray()![0];
            w.Line($"\t\t\t\t/// <summary>The '{param.Name}' argument from the most recent call.</summary>");
            w.Line($"\t\t\t\tpublic {handler.LastCallArgType} LastCallArg {{ get; private set; }}");
            w.Line();
        }
        else if (handler.LastCallArgsType != null)
        {
            w.Line("\t\t\t\t/// <summary>The arguments from the most recent call.</summary>");
            w.Line($"\t\t\t\tpublic {handler.LastCallArgsType} LastCallArgs {{ get; private set; }}");
            w.Line();
        }

        w.Line("\t\t\t\t/// <summary>True if this method was called at least once with these type arguments.</summary>");
        w.Line("\t\t\t\tpublic bool WasCalled => CallCount > 0;");
        w.Line();

        // OnCall method (returns IMethodTracking for consistency with regular method interceptors)
        w.Line("\t\t\t\t/// <summary>Sets the callback invoked when this method is called. Returns this handler for tracking.</summary>");
        w.Line($"\t\t\t\tpublic global::KnockOff.IMethodTracking OnCall({handler.MethodName}Delegate callback) {{ _onCall = callback; return this; }}");
        w.Line();

        // Callback property for internal use by invocation logic
        w.Line("\t\t\t\t/// <summary>Gets the configured callback (internal use).</summary>");
        w.Line($"\t\t\t\tinternal {handler.MethodName}Delegate? Callback => _onCall;");
        w.Line();

        // RecordCall
        w.Line("\t\t\t\t/// <summary>Records a method call.</summary>");
        if (handler.NonGenericParameters.Count == 0)
        {
            w.Line("\t\t\t\tpublic void RecordCall() => CallCount++;");
        }
        else if (handler.NonGenericParameters.Count == 1)
        {
            var param = handler.NonGenericParameters.GetArray()![0];
            w.Line($"\t\t\t\tpublic void RecordCall({param.Type} {param.Name}) {{ CallCount++; LastCallArg = {param.Name}; }}");
        }
        else
        {
            var paramList = string.Join(", ", handler.NonGenericParameters.Select(p => $"{p.Type} {p.Name}"));
            var tupleConstruction = string.Join(", ", handler.NonGenericParameters.Select(p => p.Name));
            w.Line($"\t\t\t\tpublic void RecordCall({paramList}) {{ CallCount++; LastCallArgs = ({tupleConstruction}); }}");
        }
        w.Line();

        // Reset - clears tracking state but preserves configuration (OnCall callback)
        w.Line("\t\t\t\t/// <summary>Resets tracking state (CallCount, LastCallArg/LastCallArgs) but preserves configuration (OnCall).</summary>");
        if (handler.NonGenericParameters.Count == 0)
        {
            w.Line("\t\t\t\tpublic void Reset() { CallCount = 0; }");
        }
        else if (handler.NonGenericParameters.Count == 1)
        {
            w.Line("\t\t\t\tpublic void Reset() { CallCount = 0; LastCallArg = default; }");
        }
        else
        {
            w.Line("\t\t\t\tpublic void Reset() { CallCount = 0; LastCallArgs = default; }");
        }
        w.Line();

        // Verify methods - new API throws VerificationException
        w.Line("\t\t\t\t/// <summary>Verifies call count is at least once. Throws VerificationException if not.</summary>");
        w.Line("\t\t\t\tpublic void Verify() => Verify(global::KnockOff.Times.AtLeastOnce);");
        w.Line();

        w.Line("\t\t\t\t/// <summary>Verifies call count satisfies the Times constraint. Throws VerificationException if not.</summary>");
        w.Line("\t\t\t\tpublic void Verify(global::KnockOff.Times times)");
        w.Line("\t\t\t\t{");
        w.Line("\t\t\t\t\tif (!times.Validate(CallCount))");
        w.Line("\t\t\t\t\t\tthrow new global::KnockOff.VerificationException(new global::KnockOff.VerificationFailure(\"method\", times, CallCount));");
        w.Line("\t\t\t\t}");
        w.Line();

        // Verifiable methods
        w.Line("\t\t\t\t/// <summary>Marks for verification by Stub.Verify(). Returns this for fluent chaining.</summary>");
        w.Line("\t\t\t\tpublic global::KnockOff.IMethodTracking Verifiable() => this;");
        w.Line();

        w.Line("\t\t\t\t/// <summary>Marks for verification by Stub.Verify() with Times constraint. Returns this for fluent chaining.</summary>");
        w.Line("\t\t\t\tpublic global::KnockOff.IMethodTracking Verifiable(global::KnockOff.Times times) => this;");

        w.Line("\t\t\t}");
    }

